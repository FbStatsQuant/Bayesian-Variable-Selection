#!/usr/bin/env python3
"""Campaign 2 results tables and figures, built from one run_pipeline.py output directory.

Reads only the pipeline outputs (study_metrics_mcse.csv, paired_comparisons.csv, T5_runtime.csv,
joined_scored_rows.csv, registry/registry.csv). Every number traces to those files; no rescoring.

    python make_results.py --analysis <run_pipeline out dir> --out <results dir>

Conventions (from the benchmark and run_pipeline.py): denominators include failed and missing fits,
which count as non-recovery; TP/FP/FN means use successful fits only; MCSE = sd/sqrt(n) per cell, and
fixed-stratum pooling over scenarios.
"""
import argparse
import collections
import csv
import json
import math
from pathlib import Path

import matplotlib
matplotlib.use("Agg")
import matplotlib.pyplot as plt  # noqa: E402

SCALES = ("c100", "c050")
PS = ("500", "1000")
SCEN = [str(s) for s in range(1, 7)]
MAIN8 = ["A1", "A2", "A3", "F1", "F2", "F3", "F4", "F5"]
NAMES = {"A1": "SuSiE (A1)", "A2": "Spike-and-slab LASSO (A2)", "A3": "Horseshoe (A3)", "F1": "Lasso (F1)",
         "F2": "Elastic net (F2)", "F3": "Adaptive lasso (F3)", "F4": "MCP (F4)", "F5": "ABESS / L0 (F5)",
         "SuSiE-L100": "SuSiE L=100", "SSL-RS": "SSL-RS", "F4_SCAD": "SCAD", "SuSiE-refine": "SuSiE-refine",
         "SMCBVS": "SMC-BVS v3"}
R1_FLAG_CODES = ["final_check_E1", "final_check_E2", "final_check_E3", "low_empirical_ESS", "grid_unconverged", "local_limit"]
R1_INFO_CODES = ["escalated", "cut_group", "near_tie_truncated", "forced_pilot_steps", "exact_branch",
                 "local_certified_false", "global_certified"]
SMC_BLUE, OTHER_ORANGE = "#2a78d6", "#eb6834"   # dataviz reference palette, categorical slots 1-2


def read(path):
    with Path(path).open(newline="", encoding="utf-8-sig") as f:
        return list(csv.DictReader(f))


def write(path, rows, fields=None):
    rows = list(rows)
    fields = fields or list(dict.fromkeys(k for r in rows for k in r))
    with Path(path).open("w", newline="", encoding="utf-8") as f:
        w = csv.DictWriter(f, fields)
        w.writeheader()
        for r in rows:
            w.writerow({k: ("NA" if v is None else v) for k, v in r.items()})


def num(x):
    return None if x in (None, "", "NA") else float(x)


def fmt_rate(row):
    return f'{int(float(row["exact_all_sum"]))}' if row else "-"


def fmt_mcse(x):
    x = num(x)
    return "NA" if x is None else f"{x:.3f}"


def quantile7(x, q):
    x = sorted(x)
    if not x:
        return None
    pos = (len(x) - 1) * q
    lo, hi = math.floor(pos), math.ceil(pos)
    return x[lo] + (pos - lo) * (x[hi] - x[lo])


def md_table(header, rows):
    out = ["| " + " | ".join(header) + " |", "|" + "|".join("---" for _ in header) + "|"]
    out += ["| " + " | ".join(str(c) for c in r) + " |" for r in rows]
    return "\n".join(out)


def main():
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--analysis", type=Path, required=True)
    ap.add_argument("--out", type=Path, required=True)
    a = ap.parse_args()
    an = a.analysis.resolve(); out = a.out.resolve(); out.mkdir(parents=True, exist_ok=False)
    S = read(an / "study_metrics_mcse.csv")
    P = read(an / "paired_comparisons.csv")
    T5 = read(an / "T5_runtime.csv")
    J = [r for r in read(an / "joined_scored_rows.csv") if r["method_id"] == "SMCBVS"]
    reps = len(json.loads((an / "manifest.json").read_text())["assessment_selection"]["selector"]["replicate"])
    cell = {(r["method_id"], r["rule_id"], r["scale_key"], r["p"], r["scenario"]): r for r in S}
    roles = {(r["method_id"], r["rule_id"], r["scale_key"]): (r["role"], r["label"]) for r in S}

    # Rules shown in headline tables: SMC hpm (primary) and pip05 (S0), then each of the 8 benchmark
    # methods' role=primary rules (pre-declared first), then the S1 arms. All rules stay in the long CSV.
    def headline_rules(sk):
        rules = [("SMCBVS", "hpm"), ("SMCBVS", "pip05")]
        for m in MAIN8:
            rules += sorted([(mm, rr) for (mm, rr, s), (role, _) in roles.items() if mm == m and s == sk and role == "primary"],
                            key=lambda x: ("K37" in x[1] or "lam" in x[1] or "smax" in x[1], x[1]))
        rules += sorted({(mm, rr) for (mm, rr, s), (role, _) in roles.items()
                         if s == sk and role == "S1" and rr in ("pip05", "ssl_final", "ebic1")})
        return [r for r in rules if (r[0], r[1], sk) in roles]

    def label(m, r, sk):
        lab = roles[(m, r, sk)][1]
        tag = "" if lab.startswith("pre-declared") or m == "SMCBVS" else (" (post hoc)" if "post hoc" in lab else
              " (added after c=1 seen)" if "after the c = 1" in lab else " (prereg. c050)" if "PREREG" in lab else "")
        return f"{NAMES.get(m, m)} `{r}`{tag}"

    md = [f"# Results tables (generated by make_results.py from `{an}`)\n",
          f"Replicates per (scenario, p, scale) cell: {reps}; pooled over S1-S6: {6*reps}. "
          "Counts are datasets with exact recovery of the true 14-variable model; failed or missing fits count as misses.\n"]

    # 1. Exact recovery, every cell, long form (all rules).
    long_fields = ["method_id", "rule_id", "role", "label", "scale_key", "p", "scenario", "n_expected", "n_success",
                   "n_missing", "n_fail_total", "n_flagged", "exact_all_sum", "exact_all_mean", "exact_all_mcse",
                   "exact_passing_sum", "err_exact", "err_extra_only", "err_missed_only", "err_mixed", "err_failed",
                   "tp_mean", "tp_mcse", "fp_mean", "fp_mcse", "fn_mean", "fn_mcse", "tp_n"]
    write(out / "exact_recovery_long.csv", [{k: r.get(k) for k in long_fields} for r in S], long_fields)

    for sk in SCALES:
        rules = headline_rules(sk)
        hdr = ["Method / rule"] + [f"p{p} S{s}" for p in PS for s in SCEN] + [f"p{p} pooled /{6*reps}" for p in PS]
        rows = []
        for m, r in rules:
            rows.append([label(m, r, sk)] + [fmt_rate(cell.get((m, r, sk, p, s))) for p in PS for s in SCEN]
                        + [fmt_rate(cell.get((m, r, sk, p, "pooled"))) for p in PS])
        md.append(f"\n## 1{'a' if sk=='c100' else 'b'}. Exact recovery, {sk} (c = {1 if sk=='c100' else 0.5}); count out of {reps} per scenario\n")
        md.append(md_table(hdr, rows))
        rows = []
        for m, r in rules:
            rows.append([label(m, r, sk)] + [f'{num(cell[(m, r, sk, p, "pooled")]["exact_all_mean"]):.3f} ± {fmt_mcse(cell[(m, r, sk, p, "pooled")]["exact_all_mcse"])}'
                                             if (m, r, sk, p, "pooled") in cell else "-" for p in PS])
        md.append(f"\nPooled rate ± MCSE ({sk}):\n")
        md.append(md_table(["Method / rule", "p = 500", "p = 1000"], rows))

    # 2. Error types and TP/FP/FN.
    for sk in SCALES:
        rows = []
        for m, r in headline_rules(sk):
            for p in PS:
                c = cell.get((m, r, sk, p, "pooled"))
                if not c:
                    continue
                rows.append([label(m, r, sk), p, c["err_exact"], c["err_extra_only"], c["err_missed_only"], c["err_mixed"],
                             c["err_failed"], c["n_missing"],
                             *[("NA" if num(c[f"{x}_mean"]) is None else f'{num(c[f"{x}_mean"]):.2f}') for x in ("tp", "fp", "fn")]])
        md.append(f"\n## 2{'a' if sk=='c100' else 'b'}. Error types and mean TP/FP/FN (successful fits), {sk}, pooled S1-S6\n")
        md.append(md_table(["Method / rule", "p", "exact", "extra only", "missed only", "mixed", "failed", "missing",
                            "TP", "FP", "FN"], rows))
        rows = []
        for p in PS:
            for s in SCEN:
                c = cell.get(("SMCBVS", "hpm", sk, p, s))
                if c:
                    rows.append([p, f"S{s}", c["err_exact"], c["err_extra_only"], c["err_missed_only"], c["err_mixed"],
                                 c["err_failed"], c["n_missing"],
                                 *[("NA" if num(c[f"{x}_mean"]) is None else f'{num(c[f"{x}_mean"]):.2f}') for x in ("tp", "fp", "fn")]])
        md.append(f"\nSMC-BVS `hpm` by scenario ({sk}):\n")
        md.append(md_table(["p", "scenario", "exact", "extra only", "missed only", "mixed", "failed", "missing", "TP", "FP", "FN"], rows))

    # 3. SMC diagnostics: flag rates, code rates, statuses, and recovery conditional on flags (hpm rows = one per fit).
    fits = [r for r in J if r["rule_id"] == "hpm"]
    flag_rows, cond_rows, code_rows = [], [], []
    for sk in SCALES:
        for p in PS:
            for s in SCEN + ["pooled"]:
                fs = [r for r in fits if r["scale_key"] == sk and r["p"] == p and (s == "pooled" or r["scenario"] == s)]
                n_exp = reps * (6 if s == "pooled" else 1)
                codes = collections.Counter(c for r in fs for c in set(r["diag_codes"].split(";")) if c not in ("", "NA"))
                status = collections.Counter(r["status"] for r in fs)
                v3 = collections.Counter(r["v3_status"] for r in fs)
                fl = [r for r in fs if r["diag_flag"] == "TRUE"]; un = [r for r in fs if r["diag_flag"] == "FALSE"]
                ex = lambda rs: sum(r["exact"] == "TRUE" for r in rs)
                flag_rows.append(dict(scale_key=sk, p=p, scenario=s, n_expected=n_exp, n_fits=len(fs), n_missing=n_exp - len(fs),
                                      n_flagged=len(fl), flag_rate=len(fl) / len(fs) if fs else None,
                                      **{"n_" + c: codes.get(c, 0) for c in R1_FLAG_CODES + R1_INFO_CODES},
                                      **{"status_" + k: v for k, v in sorted(status.items())},
                                      **{"v3_" + k: v for k, v in sorted(v3.items())}))
                cond_rows.append(dict(scale_key=sk, p=p, scenario=s, n_flagged=len(fl), exact_flagged=ex(fl),
                                      rate_flagged=ex(fl) / len(fl) if fl else None, n_unflagged=len(un), exact_unflagged=ex(un),
                                      rate_unflagged=ex(un) / len(un) if un else None))
                for c in R1_FLAG_CODES + R1_INFO_CODES:
                    w = [r for r in fs if c in r["diag_codes"].split(";")]; wo = [r for r in fs if c not in r["diag_codes"].split(";")]
                    if w:
                        code_rows.append(dict(scale_key=sk, p=p, scenario=s, code=c, n_with=len(w), exact_with=ex(w),
                                              n_without=len(wo), exact_without=ex(wo)))
    write(out / "smc_flag_rates.csv", flag_rows)
    write(out / "smc_recovery_given_flag.csv", cond_rows)
    write(out / "smc_recovery_given_code.csv", code_rows,
          ["scale_key", "p", "scenario", "code", "n_with", "exact_with", "n_without", "exact_without"])
    md.append("\n## 3. SMC-BVS diagnostic flags (one row per fit; R-1 `diag_flag`)\n")
    rows = []
    for r in flag_rows:
        rows.append([r["scale_key"], r["p"], r["scenario"], f'{r["n_fits"]}/{r["n_expected"]}', r["n_flagged"],
                     *[r["n_" + c] for c in R1_FLAG_CODES], r["n_cut_group"], r["n_escalated"]])
    md.append(md_table(["scale", "p", "scenario", "fits/expected", "flagged", *[c.replace("final_check_", "") for c in R1_FLAG_CODES],
                        "cut_group (info)", "escalated (info)"], rows))
    md.append("\nRecovery conditional on the flag (exact / fits):\n")
    md.append(md_table(["scale", "p", "scenario", "flagged: exact/n", "unflagged: exact/n"],
                       [[r["scale_key"], r["p"], r["scenario"], f'{r["exact_flagged"]}/{r["n_flagged"]}',
                         f'{r["exact_unflagged"]}/{r["n_unflagged"]}'] for r in cond_rows]))
    pooled_codes = [r for r in code_rows if r["scenario"] == "pooled"]
    if pooled_codes:
        md.append("\nRecovery with and without each code, pooled S1-S6 (exact / fits):\n")
        md.append(md_table(["scale", "p", "code", "with code", "without code"],
                           [[r["scale_key"], r["p"], r["code"], f'{r["exact_with"]}/{r["n_with"]}', f'{r["exact_without"]}/{r["n_without"]}']
                            for r in pooled_codes]))

    # 4. Runtime: SMC per cell from the fit rows; every method pooled from T5 (one runtime per fit).
    rt_rows = []
    for sk in SCALES:
        for p in PS:
            for s in SCEN + ["pooled"]:
                x = [num(r["runtime_s"]) for r in fits if r["scale_key"] == sk and r["p"] == p
                     and (s == "pooled" or r["scenario"] == s) and num(r["runtime_s"]) is not None]
                rt_rows.append(dict(scale_key=sk, p=p, scenario=s, n=len(x),
                                    median_s=quantile7(x, .5), mean_s=sum(x) / len(x) if x else None,
                                    p95_s=quantile7(x, .95), max_s=max(x) if x else None, total_core_h=sum(x) / 3600 if x else 0))
    write(out / "smc_runtime.csv", rt_rows)
    md.append("\n## 4. Runtime (seconds per fit; SMC-BVS from its own fit timer, others from the benchmark T5)\n")
    md.append(md_table(["scale", "p", "scenario", "n", "median", "mean", "p95", "max"],
                       [[r["scale_key"], r["p"], r["scenario"], r["n"], *[("NA" if r[k] is None else f"{r[k]:.0f}")
                         for k in ("median_s", "mean_s", "p95_s", "max_s")]] for r in rt_rows if r["scenario"] == "pooled"]))
    md.append("\nAll methods, pooled S1-S6 (T5):\n")
    md.append(md_table(["method", "scale", "p", "fits with runtime", "median", "p95", "max"],
                       [[NAMES.get(r["method_id"], r["method_id"]), r["scale_key"], r["p"], r["n_fits_with_runtime"],
                         *[("NA" if num(r[k]) is None else f"{num(r[k]):.1f}") for k in ("median_s", "p95_s", "max_s")]]
                        for r in sorted(T5, key=lambda r: (r["scale_key"] != "c100", r["method_id"], int(r["p"])))]))

    # 5. Paired comparisons: SMC hpm minus each headline benchmark rule, same datasets.
    pc = {(r["method_id"], r["rule_id"], r["scale_key"], r["p"], r["scenario"], r["smc_rule"]): r for r in P}
    rows = []
    for sk in SCALES:
        for m, r in headline_rules(sk)[2:]:
            for p in PS:
                c = pc.get((m, r, sk, p, "pooled", "hpm"))
                if c:
                    rows.append([sk, label(m, r, sk), p, c["wins"], c["losses"], c["ties"],
                                 f'{num(c["exact_difference_mean"]):+.3f} ± {fmt_mcse(c["exact_difference_mcse"])}'])
    md.append("\n## 5. Paired comparison on the same datasets: SMC-BVS `hpm` versus each method (pooled S1-S6)\n")
    md.append("Wins = SMC exact and the other not; losses = the reverse. Difference = SMC rate minus other rate, paired MCSE.\n")
    md.append(md_table(["scale", "comparator", "p", "SMC wins", "SMC losses", "ties", "difference ± MCSE"], rows))
    (out / "RESULTS_TABLES.md").write_text("\n".join(md) + "\n", encoding="utf-8")

    # Figures. Fig 1: heatmap of exact-recovery rate (magnitude -> one sequential hue), numbers in cells.
    for sk in SCALES:
        rules = headline_rules(sk)
        cols = [(p, s) for p in PS for s in SCEN]
        M = [[(num(cell[(m, r, sk, p, s)]["exact_all_mean"]) if (m, r, sk, p, s) in cell else float("nan")) for p, s in cols] for m, r in rules]
        fig, ax = plt.subplots(figsize=(11, 0.42 * len(rules) + 1.6))
        im = ax.imshow(M, cmap="Blues", vmin=0, vmax=1, aspect="auto")
        for i, row in enumerate(M):
            for j, v in enumerate(row):
                if v == v:
                    ax.text(j, i, f"{round(v*reps)}", ha="center", va="center", fontsize=8, color="white" if v > 0.6 else "#0b0b0b")
        ax.set_xticks(range(len(cols)), [f"S{s}" for _, s in cols], fontsize=8)
        ax.set_yticks(range(len(rules)), [label(m, r, sk).replace("`", "") for m, r in rules], fontsize=8)
        ax.axvline(5.5, color="white", lw=3)
        ax.set_title(f"Exact recovery out of {reps} datasets, {sk} (left: p = 500, right: p = 1000)", fontsize=10, loc="left")
        for sp in ax.spines.values():
            sp.set_visible(False)
        fig.colorbar(im, ax=ax, fraction=0.02, label="rate")
        fig.tight_layout(); fig.savefig(out / f"fig1_exact_heatmap_{sk}.png", dpi=150); plt.close(fig)

    # Fig 2: SMC hpm versus the best pre-declared primary rule of the 8 benchmark methods, per scenario, with MCSE.
    fig, axes = plt.subplots(2, 2, figsize=(10, 6), sharey=True)
    for i, sk in enumerate(SCALES):
        for j, p in enumerate(PS):
            ax = axes[i][j]
            prim = [(m, r) for m, r in headline_rules(sk)[2:] if m in MAIN8 and roles[(m, r, sk)][0] == "primary"
                    and roles[(m, r, sk)][1].startswith(("pre-declared", "pre-registered"))]
            for k, s in enumerate(SCEN):
                smc = cell.get(("SMCBVS", "hpm", sk, p, s))
                best = max((cell[(m, r, sk, p, s)] for m, r in prim if (m, r, sk, p, s) in cell),
                           key=lambda c: num(c["exact_all_mean"]), default=None)
                for c, col, dx in ((smc, SMC_BLUE, -0.12), (best, OTHER_ORANGE, 0.12)):
                    if c:
                        y, e = num(c["exact_all_mean"]), num(c["exact_all_mcse"]) or 0
                        ax.errorbar(k + dx, y, yerr=e, fmt="o", color=col, ms=6, capsize=0, lw=2)
                if best:
                    ax.annotate(NAMES.get(best["method_id"], best["method_id"]).split(" (")[-1].rstrip(")"),
                                (k + 0.12, num(best["exact_all_mean"])), xytext=(4, -10), textcoords="offset points", fontsize=7, color="#52514e")
            ax.set_xticks(range(6), [f"S{s}" for s in SCEN]); ax.set_ylim(-0.03, 1.03)
            ax.set_title(f"{sk}, p = {p}", fontsize=9, loc="left"); ax.grid(axis="y", color="#e6e5e1", lw=0.8)
            for sp in ("top", "right"):
                ax.spines[sp].set_visible(False)
    axes[0][0].set_ylabel("exact-recovery rate"); axes[1][0].set_ylabel("exact-recovery rate")
    h = [plt.Line2D([], [], marker="o", ls="", color=SMC_BLUE, label="SMC-BVS v3 (hpm)"),
         plt.Line2D([], [], marker="o", ls="", color=OTHER_ORANGE, label="best of the 8 benchmark methods' pre-declared primary rules (named)")]
    fig.legend(handles=h, loc="upper left", ncol=2, fontsize=8, frameon=False)
    fig.tight_layout(rect=(0, 0, 1, 0.95)); fig.savefig(out / "fig2_smc_vs_best.png", dpi=150); plt.close(fig)

    # Fig 3: SMC runtime per fit (minutes), one strip per scale x p.
    fig, ax = plt.subplots(figsize=(7, 3.2))
    groups = [(sk, p) for sk in SCALES for p in PS]
    data = [[num(r["runtime_s"]) / 60 for r in fits if r["scale_key"] == sk and r["p"] == p and num(r["runtime_s"]) is not None]
            for sk, p in groups]
    if any(data):
        ax.boxplot([d or [float("nan")] for d in data], vert=False, widths=0.5, showfliers=True,
                   medianprops=dict(color=SMC_BLUE, lw=2), flierprops=dict(marker=".", ms=3))
    ax.set_yticks(range(1, 5), [f"{sk}, p = {p}" for sk, p in groups], fontsize=8)
    ax.set_xlabel("minutes per fit (SMC-BVS v3)"); ax.grid(axis="x", color="#e6e5e1", lw=0.8)
    for sp in ("top", "right"):
        ax.spines[sp].set_visible(False)
    fig.tight_layout(); fig.savefig(out / "fig3_smc_runtime.png", dpi=150); plt.close(fig)
    print(json.dumps(dict(out=str(out), smc_fit_rows=len(fits), cells=len(S), paired=len(P))))


if __name__ == "__main__":
    main()
