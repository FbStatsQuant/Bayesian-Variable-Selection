# make_fixtures.R -- v3 reference outputs from core/ (revision D) for the engine_v4 golden tests.
# Usage (Owls, nice): Rscript make_fixtures.R <engine_v4 dir> <smcbvs4 binary> <work dir under TMPDIR>
# core/ is copied to <work>/core_copy and sourced there, so the compile cache never lands inside core/.
# Writes tests/fixtures/{prep,score,setup}/ and tests/fixtures/MANIFEST.json (sha256 of every file + provenance).
args <- commandArgs(TRUE)
eng <- normalizePath(args[1]); bin <- normalizePath(args[2]); work <- args[3]
dir.create(work, recursive = TRUE, showWarnings = FALSE)
core_src <- normalizePath(file.path(eng, "..", "core"))
core_copy <- file.path(work, "core_copy")
unlink(core_copy, recursive = TRUE); dir.create(core_copy)
file.copy(list.files(core_src, full.names = TRUE), core_copy, recursive = TRUE)
source(file.path(core_copy, "v3.R"))
source(file.path(eng, "tools", "v4_read.R"))
fx <- file.path(eng, "tests", "fixtures"); for (d in c("prep", "score", "setup")) dir.create(file.path(fx, d), recursive = TRUE, showWarnings = FALSE)
wf64 <- function(x, f) { con <- file(f, "wb"); writeBin(as.double(x), con, size = 8, endian = "little"); close(con) }
wi32 <- function(x, f) { con <- file(f, "wb"); writeBin(as.integer(x), con, size = 4, endian = "little"); close(con) }

# ---- datasets: one R-made adversarial case (X stored) + generator cases (X regenerated by the test from the spec) ----
set.seed(20261115)
n <- 50; p <- 40
X <- matrix(rnorm(n * p), n, p)
X[, 1] <- X[, 1] * 1e-8; X[, 2] <- X[, 2] * 1e8; X[, 3] <- X[, 3] + 1e6; X[, 4] <- 7          # constant -> dropped
X[, 5] <- 1 + 1e-12 * rnorm(n)                                                            # near-constant -> anchored branch
X[, 6] <- round(10 * X[, 6]); X[, 7] <- -abs(X[, 7]) * 3e-300; X[, 8] <- X[, 8] * 2^60 + 2^62
y <- X[, 9] - 0.5 * X[, 10] + 1e3 * rnorm(n) + 5e4
cases <- list(list(name = "scaled", n = n, p_raw = p, X = X, y = y, stored = TRUE))
gen_specs <- list(
  list(name = "ar2k",  design = "AR",      n = 200, p = 2000, seed = 101),
  list(name = "ind300", design = "IND",    n = 100, p = 300,  seed = 102),
  list(name = "blk400", design = "BLK",    n = 120, p = 400,  seed = 103),
  list(name = "adj500", design = "ADJ-OPP", n = 200, p = 500, seed = 104))
for (g in gen_specs) {
  raw <- file.path(work, paste0(g$name, "_raw.bin"))
  st <- system2(bin, c("gen", "--design", g$design, "--n", g$n, "--p", g$p, "--seed", g$seed, "--out", raw, "--threads", 1), stdout = FALSE)
  if (st != 0) stop("gen failed for ", g$name)
  rd <- v4_read(raw)
  X <- matrix(rd$get("X_cm"), g$n, g$p); y <- rd$get("y")
  rec <- jsonlite::fromJSON(paste0(raw, ".json"))
  cases[[length(cases) + 1]] <- c(g, list(p_raw = g$p, X = X, y = y, stored = FALSE, X_sha256 = rec$X_sha256, y_sha256 = rec$y_sha256))
}

# ---- prep golden ----
idx <- list()
for (cs in cases) {
  pr <- v3_preprocess(cs$X, cs$y, dup_components = FALSE)
  stopifnot(pr$status == "ok")
  if (cs$stored) { wf64(cs$X, file.path(fx, "prep", paste0(cs$name, "_X.f64"))); wf64(cs$y, file.path(fx, "prep", paste0(cs$name, "_y.f64"))) }
  wf64(pr$X, file.path(fx, "prep", paste0(cs$name, "_Xs.f64"))); wf64(pr$y, file.path(fx, "prep", paste0(cs$name, "_ys.f64")))
  wf64(c(pr$col_max, pr$col_mean, pr$col_sd, pr$y_max, pr$y_mean, pr$y_sd_scaled), file.path(fx, "prep", paste0(cs$name, "_stats.f64")))
  e <- list(name = cs$name, n = cs$n, p_raw = cs$p_raw, p = pr$p, kept = as.list(pr$kept), stored_X = cs$stored,
            anchored = sum(!vapply(pr$stable_centering$columns %||% list(), is.null, TRUE)))
  if (!cs$stored) e <- c(e, list(design = cs$design, seed = cs$seed, X_sha256 = cs$X_sha256, y_sha256 = cs$y_sha256))
  idx[[length(idx) + 1]] <- e
  cs$pr <- pr
  assign(paste0("PR_", cs$name), pr)
}
jsonlite::write_json(list(cases = idx, source = "core/v3_preprocess.R (revision D)", R = R.version.string),
                     file.path(fx, "prep", "index.json"), auto_unbox = TRUE, digits = NA, pretty = TRUE)

# ---- score golden: cpp_score (log_m, route) on R's standardised data ----
sidx <- list()
for (nm in c("ar2k", "ind300", "adj500", "scaled")) {
  pr <- get(paste0("PR_", nm)); ctx <- v3_context(pr$X, pr$y, orig = seq_len(pr$p))
  set.seed(7); K <- ctx$K; models <- list(integer(0))
  for (i in 1:400) { k <- sample(0:min(12, K), 1); models[[length(models) + 1]] <- sort(sample(pr$p, k)) }
  models[[length(models) + 1]] <- seq_len(min(K, pr$p))                 # the largest feasible model
  res <- lapply(models, function(S) v3_score(ctx, S))
  lens <- vapply(models, length, 1L)
  wi32(c(0L, cumsum(lens)), file.path(fx, "score", paste0(nm, "_ptr.i32")))
  wi32(unlist(models) - 1L, file.path(fx, "score", paste0(nm, "_idx.i32")))           # internal 0-based
  wf64(vapply(res, `[[`, 0, "log_m"), file.path(fx, "score", paste0(nm, "_logm.f64")))
  wf64(vapply(res, `[[`, 0, "Q"), file.path(fx, "score", paste0(nm, "_Q.f64")))
  wi32(match(vapply(res, `[[`, "", "route"), c("chol", "chol_refactor", "qr")) - 1L, file.path(fx, "score", paste0(nm, "_route.i32")))
  wf64(c(ctx$log_Cn, ctx$log_m0, ctx$log_W_K, ctx$yty), file.path(fx, "score", paste0(nm, "_consts.f64")))
  sidx[[length(sidx) + 1]] <- list(name = nm, n = ctx$n, p = ctx$p, K = ctx$K, models = length(models))
}
jsonlite::write_json(list(cases = sidx, source = "core cpp_score via v3_score (revision D)"), file.path(fx, "score", "index.json"),
                     auto_unbox = TRUE, digits = NA, pretty = TRUE)

# ---- setup golden (for WP2 and the compat start): blocks, tables log_r, start law, neighbours, pi_0 draws ----
uidx <- list()
for (nm in c("ar2k", "blk400", "adj500")) {
  pr <- get(paste0("PR_", nm)); ctx <- v3_context(pr$X, pr$y, orig = seq_len(pr$p))
  su <- v3_setup(ctx); stopifnot(inherits(su, "v3_setup"))
  bl <- su$blocks; bl_len <- lengths(bl)
  wi32(c(0L, cumsum(bl_len)), file.path(fx, "setup", paste0(nm, "_blk_ptr.i32")))
  wi32(unlist(bl) - 1L, file.path(fx, "setup", paste0(nm, "_blk_members.i32")))
  lr <- lapply(su$tables, `[[`, "log_r")
  wi32(c(0L, cumsum(lengths(lr))), file.path(fx, "setup", paste0(nm, "_code_ptr.i32")))
  wf64(unlist(lr), file.path(fx, "setup", paste0(nm, "_logr.f64")))
  if (pr$p <= 500) wf64(unlist(lapply(su$tables, `[[`, "log_m")), file.path(fx, "setup", paste0(nm, "_logm_tab.f64")))
  wf64(c(su$start$log_Zbar0, su$start$size_log_mass), file.path(fx, "setup", paste0(nm, "_start.f64")))
  nb <- su$neighbours
  wi32(c(0L, cumsum(lengths(nb))), file.path(fx, "setup", paste0(nm, "_nb_ptr.i32")))
  wi32(unlist(nb) - 1L, file.path(fx, "setup", paste0(nm, "_nb_idx.i32")))
  draws <- v3_start_draw(su$start, 2000, list(seed = 4242, stream = 200))
  wi32(c(0L, cumsum(lengths(draws))), file.path(fx, "setup", paste0(nm, "_draw_ptr.i32")))
  wi32(unlist(draws) - 1L, file.path(fx, "setup", paste0(nm, "_draw_idx.i32")))
  uidx[[length(uidx) + 1]] <- list(name = nm, n = ctx$n, p = ctx$p, B = su$B, J = length(bl), draws = 2000,
                                   draw_seed = 4242, draw_stream = 200, logm_tab = pr$p <= 500)
}
jsonlite::write_json(list(cases = uidx, source = "core v3_setup + v3_start_draw (revision D)",
                          note = "indices are internal 0-based; blocks in packing order; log_r by block then code"),
                     file.path(fx, "setup", "index.json"), auto_unbox = TRUE, digits = NA, pretty = TRUE)

# ---- manifest ----
files <- list.files(fx, recursive = TRUE); files <- files[files != "MANIFEST.json"]
man <- list(generated = format(Sys.time(), "%Y-%m-%dT%H:%M:%S%z"), host = Sys.info()[["nodename"]], R = R.version.string,
            core_cpp_key = V3_CPP_KEY, smcbvs4 = digest::digest(file = bin, algo = "sha256"),
            files = setNames(lapply(files, function(f) digest::digest(file = file.path(fx, f), algo = "sha256")), files))
jsonlite::write_json(man, file.path(fx, "MANIFEST.json"), auto_unbox = TRUE, pretty = TRUE)
cat("fixtures written:", length(files), "files,", round(sum(file.size(file.path(fx, files))) / 1e6, 2), "MB\n")
