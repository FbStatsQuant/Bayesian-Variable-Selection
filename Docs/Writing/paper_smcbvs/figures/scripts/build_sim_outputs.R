verify_vs_eng <- function(d, pmf, tag) {
  pm <- fread(pmf)[scope == "setting"]
  me <- d[, .(succ = sum(exact), FPm = mean(FP), FNm = mean(FN), F1m = mean(F1), nf = .N), by = .(setting_id, method)]
  j <- merge(me, pm[, .(setting_id = group, method, successes, FP_mean, FN_mean, F1_mean, n_fits)], by = c("setting_id", "method"))
  stopifnot(nrow(j) == nrow(me), all(j$succ == j$successes), all(j$nf == j$n_fits),
            max(abs(c(j$FPm - j$FP_mean, j$FNm - j$FN_mean, j$F1m - j$F1_mean))) < 1e-9)
  cat(sprintf("verified %s: %d setting x method rows agree with Engineering\n", tag, nrow(j)))
}
