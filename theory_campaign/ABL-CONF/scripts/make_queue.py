"""make_queue.py -- ABL-CONF: write the pre-registered fit queue (results/queue.txt) and a schedule estimate.

Each queue line: <name> <dataset_id> <scale> <arm> <seed_offset> <role> <k>
  role  test : the confirmatory paired fits, k = 1..10, seed = study method_seed + 1,000,000 + k
  role  refA : reserved arm-A reference fits,  k = 1..8,  seed = study method_seed + 2,000,000 + k
  role  refB : reserved arm-B guard fits (S1 only), k = 1..4, seed = study method_seed + 3,000,000 + k
Study method seeds lie in [5,420,001, 5,570,100], so no reserved or test seed equals any study seed.
Order: reference block first, then seed blocks k = 1..10; inside each block, longest expected fit first.
Usage: python3 make_queue.py <out_queue.txt> [<out_schedule.txt>]
"""
import sys, heapq

DESIGNS = [("p0500_S1_r001", "c100"), ("p0500_S4_r001", "c100"), ("p0500_S5_r001", "c100")]
CAP = 4500  # declared per-fit wall cap, seconds (PREREG.md section 4)
# expected seconds per (design, arm): ABL-START single-seed walls (study seed); arm B on S4 never finished in > 4 h
EXP = {("p0500_S1_r001", "A"): 569, ("p0500_S1_r001", "B"): 611, ("p0500_S1_r001", "C"): 2636,
       ("p0500_S4_r001", "A"): 1697, ("p0500_S4_r001", "B"): CAP, ("p0500_S4_r001", "C"): 2931,
       ("p0500_S5_r001", "A"): 1073, ("p0500_S5_r001", "B"): 1604, ("p0500_S5_r001", "C"): 3032}
OFF = {"test": 1_000_000, "refA": 2_000_000, "refB": 3_000_000}
SLOTS = 6  # 3 owls_run jobs x 2 single-threaded workers

def line(d, sk, arm, role, k):
    name = f"{d}_{sk}_{arm}_{role}{k:02d}"
    return (name, d, sk, arm, OFF[role] + k, role, k, min(EXP[(d, arm)], CAP))

q = []
ref = [line(d, sk, "A", "refA", k) for d, sk in DESIGNS for k in range(1, 9)]
ref += [line("p0500_S1_r001", "c100", "B", "refB", k) for k in range(1, 5)]
q += sorted(ref, key=lambda r: -r[-1])
for k in range(1, 11):
    q += sorted([line(d, sk, arm, "test", k) for d, sk in DESIGNS for arm in "ABC"], key=lambda r: -r[-1])

with open(sys.argv[1], "w") as f:
    f.write("# name dataset_id scale arm seed_offset role k   (generated by make_queue.py; do not edit)\n")
    for r in q: f.write(" ".join(str(x) for x in r[:7]) + "\n")

# list-scheduling estimate on SLOTS workers in queue order
h = [0.0] * SLOTS; heapq.heapify(h); ends = []
for r in q:
    t = heapq.heappop(h); heapq.heappush(h, t + r[-1]); ends.append((t + r[-1], r[0]))
tot = sum(r[-1] for r in q)
msg = (f"fits: {len(q)} (test {sum(r[5]=='test' for r in q)}, refA {sum(r[5]=='refA' for r in q)}, "
       f"refB {sum(r[5]=='refB' for r in q)})\nexpected core-hours: {tot/3600:.1f}\n"
       f"expected makespan on {SLOTS} slots (ABL-START timings, cap {CAP}s for S4-B): {max(h)/3600:.1f} h\n")
print(msg, end="")
if len(sys.argv) > 2:
    with open(sys.argv[2], "w") as f:
        f.write(msg)
        for e, n in ends: f.write(f"{e/3600:6.2f} h  {n}\n")
