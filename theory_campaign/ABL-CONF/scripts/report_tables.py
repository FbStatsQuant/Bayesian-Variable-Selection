"""report_tables.py -- ABL-CONF: descriptive tables for REPORT.md from summarise.R + apply_rule.py outputs.
Usage: python3 report_tables.py <results_dir>    (reads per_fit.csv, reference.csv, rule_designs.csv, rule_verdict.txt;
writes <results_dir>/REPORT_TABLES.md). Descriptive only; the verdicts come from apply_rule.py unchanged.
"""
import csv, math, os, statistics as stt, sys

R = sys.argv[1]
pf = list(csv.DictReader(open(os.path.join(R, "per_fit.csv"))))
ref = list(csv.DictReader(open(os.path.join(R, "reference.csv"))))
f = lambda x: float(x) if x not in ("", "NA", None) else float("nan")
med = lambda xs: stt.median(xs) if xs else float("nan")
fm = lambda v, d=3: "—" if (isinstance(v, float) and math.isnan(v)) else (f"{v:.{d}g}" if isinstance(v, float) else str(v))
L = ["# ABL-CONF tables (generated by scripts/report_tables.py)", ""]
L += ["## Reference (reserved arm-A seeds) and guard pool (reserved arm-B seeds, S1)", "",
      "| design | K | log Z_ref | se_ref | SD fit log Ẑ | KB | log Z_refB | se_refB | refA − refB | max |PIP_refA − PIP_refB| | best-known = S0 |",
      "|---|---|---|---|---|---|---|---|---|---|---|"]
for r in ref:
    L.append(f"| {r['design']} | {r['K']} | {fm(f(r['log_Zref']),6)} | {fm(f(r['se_ref']))} | {fm(f(r['sd_fit_ref']))} | {r['KB']} | "
             f"{fm(f(r['log_ZrefB']),6)} | {fm(f(r['se_refB']))} | {fm(f(r['refA_vs_refB']))} | {fm(f(r['pipref_A_vs_B_max']))} | {r['best_is_S0']} |")
L += ["", "## Test fits by design and arm (10 seeds each; medians over delivered fits unless stated)", "",
      "| design | arm | delivered / capped / failed / pending | median wall s (all, capped = cap) | median evals (cal + final) | median rebuilds | tier>0 | median log Ẑ err | median |err| | max |err| | median island SD | median max|ΔPIP| eq / zw | median mean|ΔPIP| eq / zw | HPM = best |",
      "|---|---|---|---|---|---|---|---|---|---|---|---|---|---|"]
for d in sorted({r["design"] for r in pf}):
    for a in "ABC":
        rs = [r for r in pf if r["design"] == d and r["arm"] == a and r["role"] == "test"]
        dl = [r for r in rs if r["status"] == "completed"]
        cnt = (len(dl), sum(r["status"] == "capped" for r in rs), sum(r["status"] not in ("completed", "capped", "pending") for r in rs),
               sum(r["status"] == "pending" for r in rs))
        walls = [f(r["wall_s"]) for r in rs if r["status"] not in ("pending",) and not math.isnan(f(r["wall_s"]))]
        g = lambda c: [f(r[c]) for r in dl if not math.isnan(f(r[c]))]
        err = g("err_logZ")
        L.append(f"| {d} | {a} | {cnt[0]} / {cnt[1]} / {cnt[2]} / {cnt[3]} | {fm(med(walls),4)} | {fm(med(g('evals_total')),3)} | "
                 f"{fm(med(g('rebuilds')))} | {sum(f(r['tier']) > 0 for r in dl)} | {fm(med(err))} | {fm(med([abs(x) for x in err]))} | "
                 f"{fm(max([abs(x) for x in err]) if err else float('nan'))} | {fm(med(g('sd_logZ_r')))} | "
                 f"{fm(med(g('pip_eq_max')))} / {fm(med(g('pip_zw_max')))} | {fm(med(g('pip_eq_mean')))} / {fm(med(g('pip_zw_mean')))} | "
                 f"{sum(r['hpm_eq_best'] == 'TRUE' for r in dl)}/{len(dl)} |")
L += ["", "## Per-pair cost and accuracy (test fits)", "",
      "| design | k | wall A / B / C (s) | status A / B / C | evals A / B / C (M) | log Ẑ err A / B / C |", "|---|---|---|---|---|---|"]
for d in sorted({r["design"] for r in pf}):
    for k in range(1, 11):
        x = {r["arm"]: r for r in pf if r["design"] == d and r["role"] == "test" and int(r["k"]) == k}
        if len(x) < 3: continue
        L.append(f"| {d} | {k} | " + " / ".join(fm(f(x[a]['wall_s']), 4) for a in "ABC") + " | " +
                 " / ".join(x[a]["status"] for a in "ABC") + " | " + " / ".join(fm(f(x[a]['evals_total']) / 1e6, 3) for a in "ABC") +
                 " | " + " / ".join(fm(f(x[a]['err_logZ'])) for a in "ABC") + " |")
for fn in ("rule_verdict.txt",):
    p = os.path.join(R, fn)
    if os.path.exists(p): L += ["", "## Rule output (apply_rule.py)", "", "```", open(p).read().rstrip(), "```"]
p = os.path.join(R, "rule_designs.csv")
if os.path.exists(p):
    rows = list(csv.DictReader(open(p))); keys = list(rows[0])
    L += ["", "## Rule per design", "", "| " + " | ".join(keys) + " |", "|" + "---|" * len(keys)]
    L += ["| " + " | ".join(r[k] for k in keys) + " |" for r in rows]
open(os.path.join(R, "REPORT_TABLES.md"), "w").write("\n".join(L) + "\n")
print(f"wrote {os.path.join(R, 'REPORT_TABLES.md')}")
