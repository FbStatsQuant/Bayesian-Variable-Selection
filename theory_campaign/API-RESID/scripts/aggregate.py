"""API-RESID aggregation of results/per_fit_shard*.csv -> results/per_fit.csv (merged), results/tables.md.
Usage: python3 -I scripts/aggregate.py results
All log masses in the CSV are natural logs; tables report log10 pi0(S0) and pi0(R2) (a probability).
"""
import csv, glob, math, os, sys
from statistics import median

res = sys.argv[1]
rows = []
for f in sorted(glob.glob(os.path.join(res, "per_fit_shard*.csv"))):
    rows += list(csv.DictReader(open(f)))
rows.sort(key=lambda r: (int(r["p"]), int(r["scenario"]), int(r["replicate"]), r["scale_key"]))
with open(os.path.join(res, "per_fit.csv"), "w", newline="") as fo:
    w = csv.DictWriter(fo, fieldnames=list(rows[0].keys())); w.writeheader(); w.writerows(rows)

V = [("v3re", "v3 (method)"), ("C_mode", "common s2(S~0)"), ("C_fix", "common C-fix"), ("C_sy2", "common s_y^2"),
     ("C_S0", "common s2(S0) [extra]"), ("C_orc", "common oracle [extra]"), ("resid1", "resid, 1 sweep"),
     ("resid3", "resid, 3 sweeps")]
L10 = math.log(10)
fl = lambda r, k: float(r[k])
def med(xs): return median(xs) if xs else float("nan")
def q(xs, a):
    xs = sorted(xs); i = a * (len(xs) - 1); lo = int(math.floor(i)); hi = min(lo + 1, len(xs) - 1)
    return xs[lo] + (xs[hi] - xs[lo]) * (i - lo)

def summ(rs, v):
    K = [int(r["K"]) for r in rs]
    lp = [fl(r, v + "_lpS0") / L10 for r in rs]
    r2 = [math.exp(fl(r, v + "_lpR2")) for r in rs]
    ms = [int(r[v + "_msize"]) for r in rs]; mt = [int(r[v + "_mtrue"]) for r in rs]
    return dict(n=len(rs), lp=med(lp), lp_q=(q(lp, .25), q(lp, .75)), r2=med(r2), ms=med(ms), mt=med(mt),
                ext=med([a - b for a, b in zip(ms, mt)]),
                eq=sum(r[v + "_meq"] == "TRUE" for r in rs), fav=sum(x > -1 for x in lp),
                cap=sum(m >= k for m, k in zip(ms, K)), big=sum(m - t >= 10 for m, t in zip(ms, mt)))

out = []
P = out.append
P("# API-RESID Step 0 tables (generated by scripts/aggregate.py; do not edit)\n")
P(f"Fits: {len(rows)}. Reproduction: max |v3 table rebuilt - engine table| = "
  f"{max(fl(r,'tab_check') for r in rows):.2e} (natural-log units); "
  f"max |log pi0(S0) rebuilt - O-LS0 record| = {max(abs(fl(r,'v3re_lpS0')-fl(r,'ls0_lpS0')) for r in rows if r['ls0_lpS0'] not in ('', 'NA')):.2e}; "
  f"start-mode size equal to the O-LS0 record in {sum(r['v3re_msize']==r['ls0_start_size'] for r in rows)}/{len(rows)}.\n")
P("Columns: med log10 pi0(S0) [IQR]; med pi0(R2); med |mode| (truths + extras); #mode = S0; #pi0(S0) > 0.1; "
  "#mode at the cap K; #mode with >= 10 extras.\n")

def table(groups, title):
    P(f"\n## {title}\n")
    for v, lab in V:
        P(f"\n### {lab} (`{v}`)\n")
        P("| cell | n | med log10 pi0(S0) [IQR] | med pi0(R2) | med mode: truths + extras | mode=S0 | pi0(S0)>0.1 | mode at K | >=10 extras |")
        P("|---|---|---|---|---|---|---|---|---|")
        for g, rs in groups:
            s = summ(rs, v)
            P(f"| {g} | {s['n']} | {s['lp']:.2f} [{s['lp_q'][0]:.1f}, {s['lp_q'][1]:.1f}] | {s['r2']:.3g} | "
              f"{s['mt']:.0f} + {s['ext']:.0f} (|mode| {s['ms']:.0f}) | {s['eq']} | {s['fav']} | {s['cap']} | {s['big']} |")

cells = {}
for r in rows: cells.setdefault((int(r["p"]), int(r["scenario"]), r["c"]), []).append(r)
pooled = {}
for r in rows: pooled.setdefault((int(r["p"]), r["c"]), []).append(r)
table([(f"p={k[0]} c={k[1]}", v) for k, v in sorted(pooled.items())] + [("all", rows)], "Pooled by p x c")
table([(f"p={k[0]} S{k[1]} c={k[2]}", v) for k, v in sorted(cells.items())], "Per cell (p x scenario x c)")

P("\n## Plug-in values (standardised y scale): median sigma^2 hat and median a = s2_orc / s2\n")
P("| cell | s2_orc | s2(S~0) (a) | C-fix (a) [med its] | s_y^2 (a) | s2(S0) (a) |")
P("|---|---|---|---|---|---|")
for k, rs in sorted(cells.items()):
    o = [fl(r, "s2_orc") for r in rs]
    def ma(key): return med([fl(r, key) for r in rs]), med([fl(r, "s2_orc") / fl(r, key) for r in rs])
    m, f, s, z = ma("s2_mode"), ma("s2_fix"), ma("s2_sy2"), ma("s2_S0")
    P(f"| p={k[0]} S{k[1]} c={k[2]} | {med(o):.3f} | {m[0]:.3f} ({m[1]:.2f}) | {f[0]:.3f} ({f[1]:.2f}) [{med([int(r['fix_its']) for r in rs]):.0f}] | "
      f"{s[0]:.3f} ({s[1]:.3f}) | {z[0]:.3f} ({z[1]:.2f}) |")

P("\n## Paired comparison with v3 (per fit): #fits where the variant's log pi0(S0) exceeds v3's by > 1 decade / is below by > 1 decade\n")
P("| variant | up >1 dec | down >1 dec | med diff (decades) |")
P("|---|---|---|---|")
for v, lab in V[1:]:
    d = [(fl(r, v + "_lpS0") - fl(r, "v3re_lpS0")) / L10 for r in rows]
    P(f"| {lab} | {sum(x > 1 for x in d)} | {sum(x < -1 for x in d)} | {med(d):.2f} |")
open(os.path.join(res, "tables.md"), "w").write("\n".join(out) + "\n")
print("\n".join(out[:4]))
