"""API-RESID: aggregate results/sweeps_shard*.csv -> results/sweeps.csv, results/sweeps_tables.md.
Usage: python3 -I scripts/aggregate_sweeps.py results [/home/fb31/ls0_work/agg_final/paired_per_fit.csv]
Check: the sweep-3 values must reproduce resid3 of results/per_fit.csv (same code path).
"""
import csv, glob, math, os, sys
from collections import Counter
from statistics import median

res = sys.argv[1]
rows = []
for f in sorted(glob.glob(os.path.join(res, "sweeps_shard*.csv"))):
    rows += list(csv.DictReader(open(f)))
rows.sort(key=lambda r: (int(r["p"]), int(r["scenario"]), r["dataset_id"], r["scale_key"]))
with open(os.path.join(res, "sweeps.csv"), "w", newline="") as fo:
    w = csv.DictWriter(fo, fieldnames=list(rows[0].keys())); w.writeheader(); w.writerows(rows)
main = {(r["dataset_id"], r["scale_key"]): r for r in csv.DictReader(open(os.path.join(res, "per_fit.csv")))}
L10 = math.log(10)
lp = lambda r, k: float(r[k]) / L10
fav = lambda r, k: lp(r, k) >= -4
out = []; P = out.append
P("# API-RESID backfit sweep convergence (generated by scripts/aggregate_sweeps.py; do not edit)\n")
dchk = [abs(float(r["s3_lpS0"]) - float(main[(r["dataset_id"], r["scale_key"])]["resid3_lpS0"])) for r in rows]
mchk = sum(r["s3_meq"] == main[(r["dataset_id"], r["scale_key"])]["resid3_meq"] for r in rows)
P(f"Fits: {len(rows)}. Check vs resid3 of per_fit.csv: max |log pi0(S0) diff| = {max(dchk):.2e}; mode = S0 flag agrees in {mchk}/{len(rows)}.\n")
fx = Counter(r["fixed_at"] for r in rows)
P("Sweep at which the start mode first repeats (NA = not within 10): " +
  ", ".join(f"{k}: {fx[k]}" for k in sorted(fx, key=lambda x: (x == 'NA', int(x) if x != 'NA' else 0))) + ".")
P(f"2-cycles seen: {sum(r['cycle2'] == 'TRUE' for r in rows)}.\n")
cells = {}
for r in rows: cells.setdefault((int(r["p"]), int(r["scenario"]), r["scale_key"]), []).append(r)
P("| cell | fixed by sweep 3 | fixed by 10 | med log10 pi0(S0) s3 / s5 / last | favourable s3 / s5 / last | mode = S0 s3 / s5 / last | med pi0(R2) s3 / last |")
P("|---|---|---|---|---|---|---|")
def line(lab, rs):
    f3 = sum(r["fixed_at"] != "NA" and int(r["fixed_at"]) <= 3 for r in rs)
    f10 = sum(r["fixed_at"] != "NA" for r in rs)
    m = lambda k: median(lp(r, k) for r in rs)
    P(f"| {lab} | {f3} | {f10} | {m('s3_lpS0'):.2f} / {m('s5_lpS0'):.2f} / {m('last_lpS0'):.2f} | "
      f"{sum(fav(r,'s3_lpS0') for r in rs)} / {sum(fav(r,'s5_lpS0') for r in rs)} / {sum(fav(r,'last_lpS0') for r in rs)} | "
      f"{sum(r['s3_meq']=='TRUE' for r in rs)} / {sum(r['s5_meq']=='TRUE' for r in rs)} / {sum(r['last_meq']=='TRUE' for r in rs)} | "
      f"{median(math.exp(float(r['s3_lpR2'])) for r in rs):.3g} / {median(math.exp(float(r['last_lpR2'])) for r in rs):.3g} |")
for k, rs in sorted(cells.items()): line(f"p={k[0]} S{k[1]} {k[2]}", rs)
line("**all**", rows)
d = [lp(r, "last_lpS0") - lp(r, "s3_lpS0") for r in rows]
P(f"\nlast vs sweep 3, per fit: up > 1 decade {sum(x > 1 for x in d)}, down > 1 decade {sum(x < -1 for x in d)}, median {median(d):+.3f} decades.")
if len(sys.argv) > 2:
    prod = {r["case_id"]: r["prod_class"] for r in csv.DictReader(open(sys.argv[2]))}
    cls = lambda r: {"exact recovery": "exact", "posterior miss": "pmiss"}.get(prod[r["dataset_id"] + "_" + r["scale_key"]], "reslim")
    nc = [r for r in rows if r["fixed_at"] == "NA"]
    P(f"\nNot fixed within 10 sweeps: {len(nc)} fits; by scenario " + ", ".join(f"S{k}: {v}" for k, v in sorted(Counter(r['scenario'] for r in nc).items())) + ".")
    P("\n## Last sweep against the study outcome\n")
    P("| study outcome | n | med log10 pi0(S0) s3 / last | favourable s3 / last | mode = S0 s3 / last | med pi0(R2) s3 / last | not fixed by 10 |")
    P("|---|---|---|---|---|---|---|")
    for k in ("exact", "pmiss", "reslim"):
        rs = [r for r in rows if cls(r) == k]
        P(f"| {k} | {len(rs)} | {median(lp(r,'s3_lpS0') for r in rs):.2f} / {median(lp(r,'last_lpS0') for r in rs):.2f} | "
          f"{sum(fav(r,'s3_lpS0') for r in rs)} / {sum(fav(r,'last_lpS0') for r in rs)} | "
          f"{sum(r['s3_meq']=='TRUE' for r in rs)} / {sum(r['last_meq']=='TRUE' for r in rs)} | "
          f"{median(math.exp(float(r['s3_lpR2'])) for r in rs):.3f} / {median(math.exp(float(r['last_lpR2'])) for r in rs):.3f} | {sum(r['fixed_at']=='NA' for r in rs)} |")
    P("\n| resource-limit fit | fixed_at | last log10 pi0(S0) | last mode truths/size | last mode = S0 |")
    P("|---|---|---|---|---|")
    for r in rows:
        if cls(r) == "reslim":
            P(f"| {r['dataset_id']} {r['scale_key']} | {r['fixed_at']} | {lp(r,'last_lpS0'):.2f} | {r['last_mtrue']}/{r['last_msize']} | {r['last_meq']} |")
open(os.path.join(res, "sweeps_tables.md"), "w").write("\n".join(out) + "\n")
print("\n".join(out))
