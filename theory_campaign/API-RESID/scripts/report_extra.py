"""API-RESID supplementary tables -> results/extra_tables.md.
Usage: python3 -I scripts/report_extra.py results /home/fb31/ls0_work/agg_final/paired_per_fit.csv
Adds to tables.md: (a) O-DILUTE's favourable criterion Q_f*pi0(S0) >= 1, Q_f = 1e4 (log10 pi0(S0) >= -4);
(b) the flooding check F-SIGMA §10 Step 0 asks for; (c) a cross-tab of the start variants against the
study outcome of the same fit (prod_class from O-LS0's paired_per_fit.csv: exact recovery / posterior miss /
resource limit); (d) resid1 -> resid3 movement.
"""
import csv, math, os, sys
from statistics import median

res, prodf = sys.argv[1], sys.argv[2]
rows = list(csv.DictReader(open(os.path.join(res, "per_fit.csv"))))
prod = {r["case_id"]: r["prod_class"] for r in csv.DictReader(open(prodf))}
for r in rows:
    r["cls"] = {"exact recovery": "exact", "posterior miss": "pmiss"}.get(prod[r["dataset_id"] + "_" + r["scale_key"]], "reslim")
L10 = math.log(10)
lp = lambda r, v: float(r[v + "_lpS0"]) / L10
V = [("v3re", "v3"), ("C_mode", "C s2(S~0)"), ("C_fix", "C-fix"), ("C_sy2", "C s_y^2"), ("resid1", "resid 1"), ("resid3", "resid 3")]
cells = {}
for r in rows: cells.setdefault((int(r["p"]), int(r["scenario"]), r["c"]), []).append(r)
out = []; P = out.append
P("# API-RESID supplementary tables (generated by scripts/report_extra.py; do not edit)\n")
P(f"Study outcome of the 2,400 fits: " + ", ".join(f"{k} {sum(r['cls']==k for r in rows)}" for k in ("exact", "pmiss", "reslim")) + ".\n")

P("\n## (a) Favourable fits, O-DILUTE criterion log10 pi0(S0) >= -4 (of 100 per cell)\n")
P("| cell | " + " | ".join(l for _, l in V) + " |"); P("|---" * (len(V) + 1) + "|")
tot = {v: 0 for v, _ in V}
for k, rs in sorted(cells.items()):
    c = {v: sum(lp(r, v) >= -4 for r in rs) for v, _ in V}
    for v in c: tot[v] += c[v]
    P(f"| p={k[0]} S{k[1]} c={k[2]} | " + " | ".join(str(c[v]) for v, _ in V) + " |")
P("| **all (of 2,400)** | " + " | ".join(f"**{tot[v]}**" for v, _ in V) + " |")

P("\n## (b) Flooding check (F-SIGMA §10 Step 0): #fits whose start mode has >= 10 extras / sits at the cap K = 100 (of 100)\n")
P("| cell | C s2(S~0) | C-fix | C s_y^2 | resid 3 |"); P("|---|---|---|---|---|")
for k, rs in sorted(cells.items()):
    f = lambda v: f"{sum(int(r[v+'_msize'])-int(r[v+'_mtrue'])>=10 for r in rs)} / {sum(int(r[v+'_msize'])>=int(r['K']) for r in rs)}"
    P(f"| p={k[0]} S{k[1]} c={k[2]} | {f('C_mode')} | {f('C_fix')} | {f('C_sy2')} | {f('resid3')} |")

P("\n## (c) resid 3 against the study outcome of the same fit\n")
P("| study outcome | n | med log10 pi0(S0) v3 | med log10 pi0(S0) resid3 | resid3 favourable (>= -4) | resid3 pi0(S0) > 0.1 | resid3 mode = S0 | med pi0(R2) v3 / resid3 |")
P("|---|---|---|---|---|---|---|---|")
for k in ("exact", "pmiss", "reslim"):
    rs = [r for r in rows if r["cls"] == k]
    P(f"| {k} | {len(rs)} | {median(lp(r,'v3re') for r in rs):.2f} | {median(lp(r,'resid3') for r in rs):.2f} | "
      f"{sum(lp(r,'resid3')>=-4 for r in rs)} | {sum(lp(r,'resid3')>-1 for r in rs)} | {sum(r['resid3_meq']=='TRUE' for r in rs)} | "
      f"{median(math.exp(float(r['v3re_lpR2'])) for r in rs):.3f} / {median(math.exp(float(r['resid3_lpR2'])) for r in rs):.3f} |")
P("\nThe resource-limit fits individually:\n")
P("| fit | v3 log10 pi0(S0) | resid3 log10 pi0(S0) | resid3 mode: truths/size | resid3 mode = S0 |"); P("|---|---|---|---|---|")
for r in rows:
    if r["cls"] == "reslim":
        P(f"| {r['dataset_id']} {r['scale_key']} | {lp(r,'v3re'):.2f} | {lp(r,'resid3'):.2f} | {r['resid3_mtrue']}/{r['resid3_msize']} | {r['resid3_meq']} |")

P("\n## (d) resid 1 -> resid 3 (sweep movement; sweep 2 not recorded)\n")
d = [lp(r, "resid3") - lp(r, "resid1") for r in rows]
P(f"- median change in log10 pi0(S0) from sweep 1 to sweep 3: {median(d):+.2f} decades; up > 1 decade in {sum(x>1 for x in d)}, down > 1 decade in {sum(x<-1 for x in d)} of {len(rows)}.")
P(f"- start-mode size changed between sweep 1 and sweep 3 in {sum(r['resid1_msize']!=r['resid3_msize'] for r in rows)} fits; "
  f"mode = S0 after sweep 1: {sum(r['resid1_meq']=='TRUE' for r in rows)}, after sweep 3: {sum(r['resid3_meq']=='TRUE' for r in rows)}.")
dv = [lp(r, "resid3") - lp(r, "v3re") for r in rows]
P(f"- resid3 vs v3, paired: up > 1 decade in {sum(x>1 for x in dv)}, down > 1 decade in {sum(x<-1 for x in dv)}; median {median(dv):+.2f} decades.")
open(os.path.join(res, "extra_tables.md"), "w").write("\n".join(out) + "\n")
print("\n".join(out))
