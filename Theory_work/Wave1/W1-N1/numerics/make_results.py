"""Archive the per-design outputs into numerics/json/ and generate numerics/RESULTS.md (v2, after sweep SW1).

Usage:
  py -3.13 make_results.py --archive <scratch dir with d0..d9>   # copy small outputs into json/dN/, write MANIFEST.sha256
  py -3.13 make_results.py                                        # build RESULTS.md from json/ only (durable layout)
Fails loudly (AssertionError) if a design or MC configuration is missing, a statistic is not finite, an N1 residual exceeds
1e-10, a negative control is below 1e-6, |z| > 4, or z_E > 4.
"""
import glob
import hashlib
import json
import math
import os
import shutil
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
JD = os.path.join(HERE, "json")
DESIGNS = list(range(10))
MC_TAGS = ["N2_R200000", "N8_R50000"]
SMALL = ["meta.txt", "phis.txt", "omega.tsv", "exact_results.json", "export.log"] + [f"mc_results_{t}.json" for t in MC_TAGS]


def archive(sp):
    lines = []
    for d in DESIGNS:
        src, dst = os.path.join(sp, f"d{d}"), os.path.join(JD, f"d{d}")
        os.makedirs(dst, exist_ok=True)
        for f in SMALL:
            shutil.copy2(os.path.join(src, f), os.path.join(dst, f))
        for f in sorted(os.listdir(src)):   # hashes of everything, including the large binaries not archived
            h = hashlib.sha256(open(os.path.join(src, f), "rb").read()).hexdigest()
            lines.append(f"{h}  d{d}/{f}")
    open(os.path.join(JD, "MANIFEST.sha256"), "w").write("\n".join(lines) + "\n")


def esc(x):
    return str(x).replace("|", "\\|")


def build():
    L = []
    w = L.append
    ex, meta, phis = {}, {}, {}
    for d in DESIGNS:
        dd = os.path.join(JD, f"d{d}")
        ex[d] = json.load(open(os.path.join(dd, "exact_results.json")))
        meta[d] = {l.split()[0]: l.split()[1:] for l in open(os.path.join(dd, "meta.txt")) if l.strip()}
        phis[d] = [l.split() for l in open(os.path.join(dd, "phis.txt"))]
    mc = {}
    for d in DESIGNS:
        for t in MC_TAGS:
            mc[(d, t)] = json.load(open(os.path.join(JD, f"d{d}", f"mc_results_{t}.json")))
    w("# W1-N1 numerical companion — results (v2)\n")
    w("Generated by `numerics/make_results.py` from the archived per-design outputs in `numerics/json/dN/` (exact: `n1_exact.py`;")
    w("Monte Carlo: `n1_mc.py`; both driven by `cpp/n1_harness_v2.exe`). Build and regeneration commands: `numerics/BUILD.md`.")
    w("SHA-256 of every output, including the kernel binaries and raw Monte Carlo endpoints that are not archived (size):")
    w("`numerics/json/MANIFEST.sha256`. Production headers: `numerics/cpp/production_headers.sha256`; instrumentation diff")
    w("`numerics/cpp/instr.diff` (2 read-only lines). All numbers are floating-point computations, not certified arithmetic.\n")
    w("Designs (`cpp/n1_harness.cpp` `design_of`): kind 0 iid; 1 equicorrelated; 2 AR(1); 3 exact duplicate column (col p−1 =")
    w("col 0); 4 two equicorrelated blocks with separate common factors. Grid: **pilot-derived** — production adaptive pilot")
    w("(stream 0) for the targets, then production `build_grid` on an *enumerated* V (top-20p by lg0 and by lg1 over all of Ω,")
    w("plus ∅). Production instead ranks calibration's scored-model leader stores and iterates rebuilds; N1 holds for any frozen")
    w("grid, so this affects fidelity of the grid, not the scope of the check.\n")

    w("## 1. Inputs and elementary-kernel extraction\n")
    w("Every transition probability of every elementary step is obtained from the production step function on scripted")
    w("uniforms (discrete choices at interval midpoints; every probability threshold — Gibbs inclusion, swap and independence")
    w("acceptance — by bisection on the production outcome down to adjacent doubles). Two quantities come from production")
    w("tables: the π₀ law of each target (product of the production cumulative-table widths along its scripted path; every")
    w("script is validated by calling production `draw_pi0` and checking the returned model and full consumption), and the RB")
    w("recording o_j (cross-check only).\n")
    w("| design | kind | n | p | #Ω | B | L | T | δ₁ | elem. row-sum err | max bisection bracket | Gibbs bisection vs RB o_j | π₀ scripts checked / failed | π₀ mass err | π₀ table law vs γ₀/Z̄₀ (rel) |")
    w("|---|---|---|---|---|---|---|---|---|---|---|---|---|---|---|")
    for d in DESIGNS:
        r, m, ph = ex[d], meta[d], phis[d]
        rerr = max(float(x[2]) for x in ph); merr = max(float(x[3]) for x in ph)
        br = max(float(x[4]) for x in ph); gd = max(float(x[5]) for x in ph)
        w(f"| d{d} | {m['kind'][0]} | {r['n']} | {r['p']} | {r['M']} | {r['B']} | {r['L']} | {len(r['grids']['pilot-derived'])-1} | {r['delta1']:.4f} | {rerr:.1e} | {br:.1e} | {gd:.1e} | {m['pi0_scripts_checked'][0]} / {m['pi0_script_failures'][0]} | {merr:.1e} | {r['pi0_prod_vs_spec_maxrel']:.1e} |")
        assert int(m["pi0_script_failures"][0]) == 0
    w("\nThe last column compares the π₀ law computed from the production cumulative tables (continuous-uniform interval masses)")
    w("with γ₀/Z̄₀ computed from production scores; it measures floating-point table/score/normalisation effects only (the")
    w("2⁻⁵³ grid of the coded uniforms is not modelled here). The largest relative values occur on very small masses and coexist")
    w("with the small absolute residuals of §3.\n")

    w("## 2. Round kernels (exact average over all orders)\n")
    w("Row sums: max_x \\|Σ_y R(x,y) − 1\\| (for #Ω > 130 computed by the order DP on transposed kernels, which gives R·1).")
    w("Invariance: max \\|q_φR_φ − q_φ\\|. Detailed balance: max \\|q(x)R(x,y) − q(y)R(y,x)\\| (#Ω ≤ 130 only).\n")
    w("| design | max row-sum err | max invariance err | max detailed-balance err |")
    w("|---|---|---|---|")
    rs_all = 0
    for d in DESIGNS:
        rc = ex[d]["round_checks"].values()
        db = [v["detailed_balance_err"] for v in rc if "detailed_balance_err" in v]
        rs = max(v["row_sum_err"] for v in rc); rs_all = max(rs_all, rs)
        w(f"| d{d} | {rs:.1e} | {max(v['invariance_err'] for v in rc):.1e} | {max(db):.1e} |" if db else
          f"| d{d} | {rs:.1e} | {max(v['invariance_err'] for v in rc):.1e} | n/a |")
    w(f"\nMax round-kernel row-sum error over all designs and φ: {rs_all:.1e}.\n")

    w("## 3. NX — exact E[W H(h)] − π(h) (tolerance 1e-10)\n")
    w("Residual = max over the h list (2 graph-edge joint inclusions, the true pair, a marginal, 1{S≠S₀}, \\|S\\|/K, normalised d,")
    w("a seeded random h ∈ [0,1]^Ω) **and** over every basis indicator 1{S = s}, s ∈ Ω, for every measured round q separately")
    w("(N1-q) and for the average H. N = 1 on all designs; N = 2 when #Ω ≤ 130 (d2, d3, d5, d6, d7, d9). Cases: the")
    w("pilot-derived grid, {0,1}, {0,½,1}, and L = 0 stress cases (L ≥ 0 is in the locked domain). 'normalised bias' =")
    w("max_h \\|E[H(h)] − π(h)\\| (unweighted), which shows the identity is not trivially satisfied.\n")
    w("| design | case | N | max residual (h list, all q) | max residual (basis, all q) | E[W] − 1 | max normalised bias |")
    w("|---|---|---|---|---|---|---|")
    worst = 0.0; maxbias = 0.0
    for d in DESIGNS:
        for cn, c in ex[d]["cases"].items():
            if cn.startswith("NC"):
                continue
            for k, v in c.items():
                resq = max(v["max_abs_err_per_q"] + [v["max_abs_err"]])
                for x in (resq, v["basis_max_abs_err_all_q"], v["EW"]):
                    assert math.isfinite(x)
                worst = max(worst, resq, v["basis_max_abs_err_all_q"], abs(v["EW"] - 1))
                maxbias = max(maxbias, v["max_abs_bias_normalised"])
                w(f"| d{d} | {esc(cn)} | {k[2:]} | {resq:.1e} | {v['basis_max_abs_err_all_q']:.1e} | {v['EW']-1:.1e} | {v['max_abs_bias_normalised']:.1e} |")
    assert worst <= 1e-10, worst
    w(f"\n**Worst residual over all designs, cases, N, h, q: {worst:.1e}** (tolerance 1e-10; checked). Largest normalised bias: {maxbias:.2f}.\n")

    w("## 4. Negative controls (exact) — must exceed 1e-6\n")
    w("NC1: burn-in and measured rounds use the φ = ½ round kernel (not π-invariant). NC2: the bridge stops at φ_{T−1} of the")
    w("pilot-derived grid (no final reweighting to π), then the same L + 4 rounds at φ = 1 are run; **exception d7**, whose")
    w("pilot-derived grid has a single interval: NC2 uses the grid {0,½,1} truncated at ½. Discrepancy = max over the h list")
    w("and over basis indicators of \\|E[W H] − π(h)\\|.\n")
    w("| design | control | N | discrepancy (h list) | discrepancy (basis) | E[W] − 1 |")
    w("|---|---|---|---|---|---|")
    ncmin, ncmax = 1e9, 0
    for d in DESIGNS:
        for cn, c in ex[d]["cases"].items():
            if not cn.startswith("NC"):
                continue
            for k, v in c.items():
                disc = max(v["max_abs_err"], v["basis_max_abs_err_all_q"])
                ncmin, ncmax = min(ncmin, disc), max(ncmax, disc)
                label = cn[:3] + (" (d7 exception)" if "exception" in cn else "")
                w(f"| d{d} | {label} | {k[2:]} | {v['max_abs_err']:.2e} | {v['basis_max_abs_err_all_q']:.2e} | {v['EW']-1:.1e} |")
    assert ncmin > 1e-6, ncmin
    w(f"\n**Control discrepancies range from {ncmin:.1e} to {ncmax:.1e}** (threshold 1e-6; checked).\n")

    w("## 5. NMC — production engine (instrumented `run_island`, pilot-derived grid)\n")
    w("W = Ẑ/Z per island. z = (mean W H(h) − π(h))/SE for the 8 summaries h of §3; rule \\|z\\| ≤ 4 (checked). Hook: max")
    w("\\|hook marginal frequency − production `pip_plain`\\| over all islands and j. Corollary E: z_E = (mean W\\|H(h) − h(S₀)\\| − δ₁)/SE")
    w("over every h ∈ [0,1] in the list, rule z_E ≤ 4 (checked; the equality case h = 1{S≠S₀} is centred at 0). NC3 (adaptive h,")
    w("chosen after the run: indicator of the island's most frequent endpoint): N1-centred statistic W·H(h_ω) − π(h_ω) (paired),")
    w("whose mean would be 0 if N1 extended to this random h; reported with its z.\n")
    w("| design | N | islands | hook diff | E[W] − 1 (z) | max \\|z\\| (h) | max z_E | NC3 N1-centred mean (z) |")
    w("|---|---|---|---|---|---|---|---|")
    zmax = 0; zEmax = -1e9; nc3 = []
    for d in DESIGNS:
        for t in MC_TAGS:
            m = mc[(d, t)]
            zs = {k: v["z"] for k, v in m["h"].items()}
            assert all(math.isfinite(z) for z in zs.values())
            kmax = max(zs, key=lambda k: abs(zs[k]))
            zE = max((v["corE_mean"] - v["corE_bound_delta1"]) / v["corE_se"] for v in m["h"].values() if "corE_mean" in v and v["corE_se"] > 0)
            a = m["adaptive_mode_h"]; z3 = a["N1_centred_mean"] / a["N1_centred_se"]; nc3.append(z3)
            zmax = max(zmax, abs(zs[kmax])); zEmax = max(zEmax, zE)
            assert m["hook_vs_pip_plain_maxdiff"] == 0.0
            w(f"| d{d} | {m['N']} | {m['reps']} | {m['hook_vs_pip_plain_maxdiff']:.0e} | {m['EW']-1:+.4f} ({(m['EW']-1)/m['EW_se']:+.2f}) | {abs(zs[kmax]):.2f} ({esc(kmax)}) | {zE:+.2f} | {a['N1_centred_mean']:+.4f} ({z3:+.1f}) |")
    assert zmax <= 4 and zEmax <= 4, (zmax, zEmax)
    ndet = sum(abs(z) > 6 for z in nc3)
    w(f"\n**Max \\|z\\| = {zmax:.2f}; max z_E = {zEmax:+.2f}** (rules checked). NC3: \\|z\\| > 6 on {ndet} of {len(nc3)} runs.\n")

    w("## 6. Reading (lead)\n")
    w(f"- NX: N1-q holds on every design, grid, N, h, basis indicator and measured round to floating-point precision (worst")
    w(f"  residual {worst:.1e}), while the unweighted endpoint average is biased by up to {maxbias:.2f}: the identity is a property of")
    w("  the evidence-weighted record, not of near-stationary particles.")
    w(f"- Controls NC1 and NC2 are detected on every design ({ncmin:.1e} to {ncmax:.1e}), so the exact check has power against a")
    w("  non-invariant terminal kernel and against a missing final reweighting.")
    w(f"- NMC: the production engine agrees with π(h) within Monte Carlo error (max \\|z\\| {zmax:.2f}; W is heavy-tailed at N = 2,")
    w("  so the largest \\|z\\| tend to co-occur with the largest E[W] − 1 deviations). The hook reproduces `pip_plain` exactly.")
    w(f"  Corollary E: z_E ≤ {zEmax:.2f} everywhere.")
    w(f"- NC3 (adaptive h): the N1-centred discrepancy is resolved (\\|z\\| > 6) on {ndet} of {len(nc3)} runs; on the remaining runs")
    w("  this experiment does not detect a discrepancy (which does not show that selection leaves the identity intact there).")
    open(os.path.join(HERE, "RESULTS.md"), "w", encoding="utf-8").write("\n".join(L) + "\n")


if __name__ == "__main__":
    if len(sys.argv) > 2 and sys.argv[1] == "--archive":
        archive(sys.argv[2])
    build()
    print("RESULTS.md written")
