"""assemble.py — generate the paper's theorem-statement blocks and provenance tables FROM the registry.

Prose stays hand-written; statements, status labels and dependency/provenance tables are generated, so a
supersession or retraction rebuilds the paper mechanically.

Output (Theory_work/INFRA/paper/generated/):
  regmacros.tex          fallbacks for \\st, statusbox, \\regflag, \\regmissing (provided only if undefined)
  blocks/<id>.tex        one block per paper claim: theorem-like environment with the LaTeX statement taken from
                         the claim's `tex` span (e.g. a FINAL section) + a statusbox with the VERBATIM status,
                         version, council and evidence. Prose does \\input{.../blocks/<id>.tex}.
                         SUPERSEDED-VALID X -> block renders the replacement Y (followed transitively), noting "supersedes X"
                         SUSPECT / REBASE-NEEDED / NARROWED / RETRACTED / DEPRECATED -> a visible \\regflag
  provenance.tex         longtable: id, name, version, state, verbatim status, council, evidence
  dependencies.tex       longtable: id -> depends_on (with each dependency's state), implies, superseded_by
  strength.tex           longtable: assumptions (with necessity verdicts), conclusion level, rate, scope, improvable
  index.tex              \\input of every block in registry order (for a review build)
  MANIFEST.txt           claim -> block file -> source span -> sha256 (diff-friendly)
Selection: claims with headline=yes (default) or every claim with a `tex` span (--all-tex).
--check: regenerate into a temp dir and exit 1 if the committed output is stale (CI).
"""
from __future__ import annotations

import argparse
import filecmp
import os
import re
import shutil
import sys
import tempfile

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import bvsreg as R  # noqa: E402

OUT = os.path.join(R.INFRA, "paper", "generated")
ENV = {"theorem": "theorem", "lemma": "lemma", "proposition": "proposition", "corollary": "corollary",
       "counterexample": "proposition", "obstruction": "proposition", "external": "theorem"}
FLAGGED = {"SUSPECT", "REBASE-NEEDED", "NARROWED", "RETRACTED", "DEPRECATED", "CANDIDATE"}

MACROS = r"""% generated by Theory_work/INFRA/tools/assemble.py — do not edit
\providecommand{\st}[1]{\textsf{#1}}
\providecommand{\regflag}[1]{\par\noindent\fbox{\parbox{\dimexpr\linewidth-2\fboxsep-2\fboxrule}{\textbf{REGISTRY FLAG:} #1}}\par}
\providecommand{\regmissing}[1]{\textup{[\textbf{No LaTeX statement registered for #1} (registry field \texttt{tex} is empty); see the Markdown statement cited in the status box.]}}
\ifcsname statusbox\endcsname\else\newenvironment{statusbox}[1][]{\par\small\noindent\textbf{Status and evidence.} }{\par}\fi
\ifcsname theorem\endcsname\else\newtheorem{theorem}{Theorem}\fi
\ifcsname lemma\endcsname\else\newtheorem{lemma}[theorem]{Lemma}\fi
\ifcsname proposition\endcsname\else\newtheorem{proposition}[theorem]{Proposition}\fi
\ifcsname corollary\endcsname\else\newtheorem{corollary}[theorem]{Corollary}\fi
\providecommand{\regref}[1]{\texttt{#1}}
"""


def esc(s: str) -> str:
    rep = {"\\": r"\textbackslash{}", "{": r"\{", "}": r"\}", "$": r"\$", "&": r"\&", "%": r"\%", "#": r"\#",
           "_": r"\_", "^": r"\^{}", "~": r"\~{}"}
    return "".join(rep.get(c, c) for c in (s or ""))


safe = R.safe


def tex_span(spec: str):
    """`path:a-b` -> list of lines of the statement (the \\begin{env}..\\end{env} block or its body)."""
    if not spec or ":" not in spec:
        return None
    path, _, span = spec.rpartition(":")
    sp = R.parse_span(span)
    lines = R.read_lines(path)
    if not sp or lines is None or sp[1] > len(lines):
        return None
    return lines[sp[0] - 1: sp[1]]


def body_of(lines):
    """Strip an outer \\begin{env}[..]\\label{..} ... \\end{env} so the generator controls env and label."""
    txt = "\n".join(lines)
    m = re.match(r"\s*\\begin\{(\w+)\}(\[[^\n]*?\])?(\\label\{[^}]*\})?(.*)\\end\{\1\}\s*$", txt, re.S)
    return (m.group(4).strip(), (m.group(2) or "")[1:-1]) if m else (txt.strip(), "")


def final_claim(by, cid, seen=None):
    seen = seen or []
    r = by[cid]
    if r["state"] == "SUPERSEDED-VALID" and r.get("superseded_by") in by and r["superseded_by"] not in seen:
        return final_claim(by, r["superseded_by"], seen + [cid])
    return r, seen


def block(by, cid, deps):
    r, chain = final_claim(by, cid)
    env = ENV.get(r["kind"], "theorem")
    lines = tex_span(r.get("tex", ""))
    L = [f"% generated from registry claim {cid} (v{by[cid]['version']}); edit the registry, not this file"]
    if chain:
        L.append(f"% {cid} is SUPERSEDED; rendering {r['id']} (chain: {' -> '.join(chain + [r['id']])})")
    if lines:
        body, title = body_of(lines)
        title = title or r["name"]
        L += [f"\\begin{{{env}}}[{title}]\\label{{reg:{safe(cid)}}}", body, f"\\end{{{env}}}"]
    else:
        L += [f"\\begin{{{env}}}[{esc(r['name'])}]\\label{{reg:{safe(cid)}}}",
              f"\\regmissing{{\\regref{{{esc(r['id'])}}}}}", f"\\end{{{env}}}"]
    if chain:
        L.append(f"\\noindent\\emph{{This result supersedes {esc(', '.join(chain))} (registry).}}")
    if r["state"] in FLAGGED:
        L.append(f"\\regflag{{{esc(r['id'])} is {r['state']}: {esc(r.get('state_reason', '')[:300])}}}")
    bad = [d for d in deps.get(r["id"], []) if by[d]["state"] in FLAGGED | {"SUPERSEDED-VALID", "CANDIDATE"}]
    if bad:
        listing = ", ".join(d + " (" + by[d]["state"] + ")" for d in bad)
        L.append(f"\\regflag{{depends on non-active claims: {esc(listing)}}}")
    ev = "; ".join(R.split_list(r.get("evidence", ""))[:4])
    L += ["\\begin{statusbox}",
          f"\\regref{{{esc(r['id'])}}} v{r['version']}: \\st{{{esc(r['status'])}}}"
          + (f". Council: {esc(r['council'])}" if r.get("council") else "")
          + (f". Evidence: {esc(ev)}" if ev else "")
          + f". Statement: \\regref{{{esc(r['file'])}:{r['lines']}}}.",
          "\\end{statusbox}", ""]
    return "\n".join(L)


def longtable(head, rows, spec):
    L = [f"\\begin{{longtable}}{{{spec}}}", " & ".join(f"\\textbf{{{h}}}" for h in head) + r" \\ \hline",
         r"\endhead"]
    L += [" & ".join(c for c in row) + r" \\" for row in rows]
    L.append(r"\end{longtable}")
    return "\n".join(L) + "\n"


def generate(outdir, all_tex=False):
    rows = R.load_claims()
    by = R.index(rows)
    deps = R.Graph(rows).deps
    sharp = R.load_sharpness()
    sel = [r for r in rows if r.get("headline") == "yes" or (all_tex and r.get("tex"))]
    os.makedirs(os.path.join(outdir, "blocks"), exist_ok=True)
    with open(os.path.join(outdir, "regmacros.tex"), "w", encoding="utf-8", newline="\n") as fh:
        fh.write(MACROS)
    man, idx = [], ["% generated: \\input every registry block", "\\input{regmacros}"]
    for r in sel:
        f = f"blocks/{safe(r['id'])}.tex"
        with open(os.path.join(outdir, f), "w", encoding="utf-8", newline="\n") as fh:
            fh.write(block(by, r["id"], deps))
        idx.append(f"\\input{{{f[:-4]}}}")
        man.append(f"{r['id']}\t{f}\t{r.get('tex') or r['file'] + ':' + r['lines']}\t{r['sha256'][:16]}\t{r['state']}")
    p = [(esc(r["id"]), esc(r["name"]), r["version"], r["state"], esc(r["status"][:200]), esc(r.get("council", "")),
          esc("; ".join(R.split_list(r.get("evidence", ""))[:3])[:200])) for r in sel]
    with open(os.path.join(outdir, "provenance.tex"), "w", encoding="utf-8", newline="\n") as fh:
        fh.write("% generated by assemble.py\n" + longtable(
            ["id", "name", "v", "state", "status (verbatim)", "council", "evidence"], p,
            "p{2.2cm}p{2.2cm}p{0.7cm}p{1.2cm}p{3.2cm}p{1.8cm}p{3cm}"))
    d = [(esc(r["id"]), esc("; ".join(f"{x} [{by[x]['state']}]" for x in deps.get(r["id"], []))),
          esc(r.get("implies", "")), esc(r.get("superseded_by", ""))) for r in sel]
    with open(os.path.join(outdir, "dependencies.tex"), "w", encoding="utf-8", newline="\n") as fh:
        fh.write("% generated by assemble.py\n" + longtable(["id", "depends on [state]", "implies", "superseded by"],
                                                              d, "p{2.6cm}p{7cm}p{2.6cm}p{2cm}"))
    s = []
    for r in sel:
        asm = "; ".join(f"{a} ({R.necessity(r['id'], R.parse_asm(a)[0], sharp)[0]})"
                        for a in R.split_list(r.get("assumptions", "")))
        s.append((esc(r["id"]), esc(asm), esc(r.get("conclusion", "")), esc(r.get("rate", "")),
                  esc(r.get("scope", "")), esc(r.get("improvable", ""))))
    with open(os.path.join(outdir, "strength.tex"), "w", encoding="utf-8", newline="\n") as fh:
        fh.write("% generated by assemble.py\n" + longtable(
            ["id", "assumptions (necessity)", "conclusion", "rate", "scope", "improvable"], s,
            "p{2.2cm}p{4.2cm}p{3cm}p{1.6cm}p{2.6cm}p{1.6cm}"))
    with open(os.path.join(outdir, "index.tex"), "w", encoding="utf-8", newline="\n") as fh:
        fh.write("\n".join(idx) + "\n")
    with open(os.path.join(outdir, "MANIFEST.txt"), "w", encoding="utf-8", newline="\n") as fh:
        fh.write("id\tblock\tsource\tsha256[:16]\tstate\n" + "\n".join(man) + "\n")
    return len(sel), sum(1 for r in sel if not tex_span(r.get("tex", "")))


def same_tree(a, b):
    c = filecmp.dircmp(a, b)
    if c.left_only or c.right_only or c.diff_files or c.funny_files:
        return False
    return all(same_tree(os.path.join(a, s), os.path.join(b, s)) for s in c.common_dirs)


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--check", action="store_true")
    ap.add_argument("--all-tex", action="store_true")
    a = ap.parse_args()
    if a.check:
        tmp = tempfile.mkdtemp()
        try:
            generate(tmp, a.all_tex)
            ok = os.path.isdir(OUT) and same_tree(tmp, OUT)
        finally:
            shutil.rmtree(tmp, ignore_errors=True)
        print("assemble --check: " + ("generated paper blocks are current" if ok else
                                       "STALE: run python Theory_work/INFRA/tools/assemble.py and commit"))
        sys.exit(0 if ok else 1)
    if os.path.isdir(OUT):
        shutil.rmtree(OUT)
    n, missing = generate(OUT, a.all_tex)
    print(f"assembled {n} blocks into {os.path.relpath(OUT, R.ROOT)} ({missing} without a LaTeX statement)")


if __name__ == "__main__":
    main()
