#!/usr/bin/env python3
"""Render registry/*.tsv into tables/registry_<group>.tex (Appendix B). stdlib only."""
import glob, os

HERE = os.path.dirname(os.path.abspath(__file__))
DOC = os.path.dirname(HERE)
COLS = ["id", "native", "kind", "short", "status_exact", "checked_by", "regime", "depends_on", "used_by",
        "open_items", "tex_label", "sources"]
GROUPS = [
    ("main", "Main cards and their clauses", {"main-card", "clause", "remark"}),
    ("supp", "Supplement cards", {"supp-card"}),
    ("oblig", "Proof obligations", {"obligation"}),
    ("future", "Future work, drops and inherent limitations", {"future-work", "drop", "limitation"}),
    ("defs", "Definitions, rulings, method decisions, dissents, cited lemmas",
     {"definition", "ruling", "method-decision", "dissent", "cited-lemma"}),
    ("history", "Campaign-history results, refutations and counterexamples",
     {"history-result", "refuted", "counterexample"}),
    ("empirical", "Empirical results", {"empirical"}),
    ("open", "Pending decisions, engineering items and the frontier", {"decision-pending", "engineering", "frontier"}),
    ("wave", "Theory loop (Waves 1 and 1C, v1.1): ticket results, audits and status changes", {"wave-result"}),
]


def esc(s):
    s = s.replace("\\|", "|")
    out = []
    for ch in s:
        out.append({"\\": r"\textbackslash{}", "&": r"\&", "%": r"\%", "$": r"\$", "#": r"\#", "_": r"\_",
                    "{": r"\{", "}": r"\}", "~": r"\textasciitilde{}", "^": r"\textasciicircum{}"}.get(ch, ch))
        if ch in "/_;,()-:=|+.":  # long unbreakable tokens (paths, status codes) may break here
            out.append(r"\allowbreak{}")
    return "".join(out)


def idcell(r):
    i = esc(r["id"])
    # IDs defined in the text link back to their definition; registry-only IDs get their anchor here,
    # so \rid{...} to them resolves to this appendix.
    return rf"\rid{{{r['id']}}}" if r["tex_label"] else rf"\hypertarget{{id:{r['id']}}}{{\texttt{{{i}}}}}"


def main():
    rows = []
    for f in sorted(glob.glob(os.path.join(DOC, "registry", "*.tsv"))):
        with open(f, encoding="utf-8") as fh:
            lines = fh.read().splitlines()
        if not lines or lines[0].split("\t") != COLS:
            continue
        for line in lines[1:]:
            c = line.split("\t")
            if len(c) == len(COLS):
                rows.append(dict(zip(COLS, c)))
    os.makedirs(os.path.join(DOC, "tables"), exist_ok=True)
    index = []
    for key, title, kinds in GROUPS:
        sel = [r for r in rows if r["kind"] in kinds]
        path = os.path.join(DOC, "tables", f"registry_{key}.tex")
        with open(path, "w", encoding="utf-8") as fh:
            fh.write(f"% generated by scripts/registry_to_tex.py — do not edit\n")
            fh.write(rf"\subsection{{{title} ({len(sel)})}}" + "\n")
            if not sel:
                fh.write(r"\emph{(no rows)}" + "\n")
                index.append(f"tables/registry_{key}")
                continue
            fh.write(r"{\scriptsize" + "\n" + r"\RaggedRight\begin{xltabular}{\textwidth}{@{}>{\RaggedRight}p{1.25cm}>{\RaggedRight}p{2.6cm}>{\RaggedRight\arraybackslash}X >{\RaggedRight}p{4.3cm}>{\RaggedRight}p{1.6cm}>{\RaggedRight\arraybackslash}p{1.7cm}@{}}" + "\n")
            fh.write(r"\toprule ID & Native name & Short description & Status (verbatim) & Regime & Depends on\\ \midrule\endhead" + "\n")
            for r in sel:
                fh.write(" & ".join([idcell(r), esc(r["native"]), esc(r["short"]), esc(r["status_exact"]),
                                     esc(r["regime"]), esc(r["depends_on"])]) + r"\\" + "\n")
            fh.write(r"\bottomrule\end{xltabular}}" + "\n")
        index.append(f"tables/registry_{key}")
    with open(os.path.join(DOC, "tables", "registry_index.tex"), "w", encoding="utf-8") as fh:
        fh.write("% generated\n" + "".join(rf"\input{{{p}}}" + "\n" for p in index))
    print(f"rendered {len(rows)} registry rows into {len(index)} tables")


if __name__ == "__main__":
    main()
