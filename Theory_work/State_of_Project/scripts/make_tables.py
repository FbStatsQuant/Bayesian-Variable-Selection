def rows(rel):
    with open(os.path.join(REPO, rel), encoding="utf-8", newline="") as f:
        return list(csv.DictReader(f))


def jload(rel):
    with open(os.path.join(REPO, rel), encoding="utf-8") as f:
        return json.load(f)


def check(name, got, want):
    ok = got == want
    print(f"CHECK {'PASS' if ok else 'FAIL'} {name}: got {got}, expected {want}")
    if not ok:
        FAILS.append(name)


def esc(s):
    return (s.replace("\\", "\\textbackslash{}").replace("_", "\\_").replace("%", "\\%")
            .replace("&", "\\&").replace("#", "\\#").replace("$", "\\$"))


def tt(s):
    return "\\texttt{" + esc(s) + "}"


def fnum(x, d):
    if x is None or x == "" or x == "NA":
        return "--"
    v = float(x)
    if d == 0:
        return f"{int(round(v)):,}".replace(",", "{,}")
    return f"{v:.{d}f}"


def sci(x, d=1):
    """3 significant digits in [0.01, 1000); otherwise m*10^e with d decimals in m."""
    if x is None or x == "" or x == "NA":
        return "--"
    v = float(x)
    if v == 0:
        return "0"
    if 0.01 <= abs(v) < 1000:
        return f"{v:.3g}"
    e = int(math.floor(math.log10(abs(v))))
    m = v / 10 ** e
    return f"${m:.{d}f}\\cdot10^{{{e}}}$"


def cname(scale):
    return {"c100": "1", "c050": "0.5"}[scale]


def write(name, src_paths, body, note=""):
    path = os.path.join(OUT, f"emp_{name}.tex")
    srcs = "; ".join(src_paths)
    head = (f"% GENERATED by scripts/make_tables.py from {srcs} -- do not edit by hand.\n")
    srcline = "\\par{\\footnotesize Generated by \\texttt{scripts/make\\_tables.py} from " + \
        "; ".join("\\src{" + p + "}" for p in src_paths) + "." + (" " + note if note else "") + "}\\par\n"
    txt = head + body + srcline
    with open(path, "w", encoding="utf-8", newline="\n") as f:
        f.write(txt)
    print(f"\n===== wrote tables/emp_{name}.tex  (sources: {srcs})")
    print(txt)


def tabular(colspec, header, lines, size="\\footnotesize", sep="4pt"):
    out = ["\\begin{center}", size, f"\\setlength{{\\tabcolsep}}{{{sep}}}",
           "\\begin{adjustbox}{max width=\\linewidth}", f"\\begin{{tabular}}{{{colspec}}}",
           "\\toprule", header + " \\\\", "\\midrule"]
    for ln in lines:
        out.append(ln if ln.endswith("\\midrule") or ln.endswith("\\addlinespace") else ln + " \\\\")
    out += ["\\bottomrule", "\\end{tabular}", "\\end{adjustbox}", "\\end{center}", ""]
    return "\n".join(out)


def longtab(colspec, header, lines, size="\\footnotesize", sep="4pt"):
    out = ["{" + size, f"\\setlength{{\\tabcolsep}}{{{sep}}}", f"\\begin{{longtable}}{{{colspec}}}", "\\toprule",
           header + " \\\\", "\\midrule", "\\endhead", "\\bottomrule", "\\endfoot"]
    for ln in lines:
        out.append(ln if ln.endswith("\\midrule") or ln.endswith("\\addlinespace") else ln + " \\\\")
    out += ["\\end{longtable}}", ""]
    return "\n".join(out)


