"""f_report.py <F1|F2|F3>: aggregate f*_results.pkl -> F*_raw.csv and F*_summary.md (pure aggregation, no new computation)."""
import sys, pickle, csv, statistics as st
import numpy as np

def load(pk):
    return pickle.load(open(pk, 'rb'))

def merge(res):
    lat = {r['id']: r for r in res if r.get('kind') == 'lat' and 'error' not in r}
    pop = {r['id']: r for r in res if r.get('kind') == 'pop' and 'error' not in r}
    errs = [r for r in res if 'error' in r]
    rows = []
    for r in res:
        if r.get('kind') != 'seed' or 'error' in r:
            continue
        d = dict(r)
        L = lat.get(r['id']); P = pop.get(r['id'])
        if L is not None:
            s = L['seeds'].index(r['seed'])
            d.update(nT=L['nT'], na_max_gain=L['na_max'][s], na_verified=L['na_verified'][s], na_arg=str(L['na_arg'][s]),
                     maxZ2=L['z2_max'][s], maxZ2_arg=str(L['z2_arg'][s]), maxZ2_minus_cstar=L['zm_max'][s], zm_arg=str(L['zm_arg'][s]),
                     tl_swap_max=L['sw_max'][s], tl_swap_verified=L['sw_verified'][s], tl_del_max=L['del_max'][s], lat_mode=L['finfo']['mode'],
                     lat_nA=L['finfo']['nA'], lat_nB=L['finfo']['nB'], lat_nC=L['finfo']['nC'])
        if P is not None:
            d.update({k: P[k] for k in ('TV', 'NEG', 'eta', 'etaA', 'nblocks', 'maxblock', 'gram_err')})
        rows.append(d)
    return rows, lat, pop, errs

def rng(v):
    v = list(v)
    return f"{min(v)}-{max(v)}" if v else "-"

def make(tag, pk, title, ROWS=None):
    res = load(pk)
    rows, lat, pop, errs = merge(res)
    keys = []
    for d in rows:
        for k in d:
            if k not in keys: keys.append(k)
    rows.sort(key=lambda d: (d['id'], d['seed']))
    with open(f'{tag}_raw.csv', 'w', newline='') as f:
        w = csv.DictWriter(f, fieldnames=keys); w.writeheader()
        for d in rows: w.writerow(d)
    ids = sorted({d['id'] for d in rows})
    out = [f"# {tag} summary: {title}", "", "Generated by f_report.py from " + pk + " (observations only). Raw per-run rows: " + f"{tag}_raw.csv.", ""]
    if errs: out += [f"**ERRORS in {len(errs)} tasks** (first): `{errs[0]['error'][-300:]}`", ""]
    hdr = ("| row | |P| | nT tested | S0⊆S~0 | S~0⊆Q | extras (min-max) | extras⊆P | NA max gain (max over seeds) | NA viol. seeds | max Z² | max(Z²−c*) | seeds Z²>c* | TL swap max | TL del max | "
           "path moves | path all-del | path→S0 | path cert | prod ell: final=S0 / S0scored / local_limit | cap: final=S0 / S0scored / local_limit |")
    out += [hdr, "|" + "---|" * (hdr.count("|") - 1)]
    for i in ids:
        R = [d for d in rows if d['id'] == i]
        n = len(R)
        c = lambda k: sum(1 for d in R if d.get(k))
        g = lambda k: [d[k] for d in R if k in d and d[k] == d[k]]
        na = g('na_max_gain'); z2 = g('maxZ2'); zm = g('maxZ2_minus_cstar'); sw = g('tl_swap_max'); dl = g('tl_del_max')
        lp = lat.get(i)
        out.append("| " + " | ".join([
            i + (f" (d_n={ROWS[i]['dn']})" if ROWS[i]['dn'] else ""), str(len(ROWS[i]['P'])), str(R[0].get('nT', '-')),
            f"{c('S0_in_start')}/{n}", f"{c('start_in_Q')}/{n}", rng([d['n_extras'] for d in R]), f"{c('extras_in_P')}/{n}",
            f"{max(na):.3g}" if na else '-', f"{sum(1 for v in na if v >= 0)}/{len(na)}",
            f"{max(z2):.3g}" if z2 else '-', f"{max(zm):.3g}" if zm else '-', f"{sum(1 for v in zm if v > 0)}/{len(zm)}",
            f"{max(sw):.3g}" if sw else '-', f"{max(dl):.3g}" if dl else '-',
            rng([d['path_moves'] for d in R if 'path_moves' in d]), f"{c('path_all_del_extras')}/{n}", f"{c('path_final_S0')}/{n}", f"{c('path_certified')}/{n}",
            f"{c('prod_final_S0')}/{c('prod_S0_scored')}/{c('prod_local_limit')} (ell={R[0].get('prod_ell')}) of {n}",
            f"{c('cap_final_S0')}/{c('cap_S0_scored')}/{c('cap_local_limit')} (ell range {rng([d.get('cap_ell') for d in R if 'cap_ell' in d])}) of {n}"]) + " |")
    out += ["", "## Population (noise-free) margins on the coded partition", "",
            "| row | n | p | B | #blocks | max block | blocks with truth | TV margin (min δ²/log n) | NEG margin (max δ²/log n) | eta (0.5·(√(2A+1)−√(2A))²) | eta_A (without 0.5) | TV>eta | NEG<eta | gram err |", "|" + "---|" * 14]
    for i in sorted(pop):
        P = pop[i]
        out.append(f"| {i} | {P['n']} | {P['p']} | {P['B']} | {P['nblocks']} | {P['maxblock']} | {P['blocks_with_truth']} | {P['TV']:.4g} | {P['NEG']:.4g} | {P['eta']:.4g} | {P['etaA']:.4g} | {P['TV'] > P['eta']} | {(P['NEG'] < P['eta']) if P['NEG']==P['NEG'] else 'n/a'} | {P['gram_err']:.2g} |")
    out += ["", "## Lattice test details (all seeds share the same tested T family per row)", "",
            "| row | nT | family sizes (A: |T\S0|<=2, B: |Q\T|<=2, C: random) | mode | worst NA pair per seed (k=|T|, |T\S0|, l, l in Q) | NA verified by bvs_core F (max abs diff vs incremental) | secs |", "|---|---|---|---|---|---|---|"]
    for i in sorted(lat):
        L = lat[i]
        sbest = int(np.argmax(L['na_max']))
        dif = max(abs(a - b) for a, b in zip(L['na_max'], L['na_verified']))
        out.append(f"| {i} | {L['nT']} | {L['finfo']['nA']}/{L['finfo']['nB']}/{L['finfo']['nC']} | {L['finfo']['mode']} | seed {sbest}: {L['na_arg'][sbest]} gain {L['na_max'][sbest]:.3f} | {dif:.2e} | {L['secs']:.0f} |")
    # per-row NA gain by seed
    out += ["", "## NA max add gain per seed (nats; must be <0)", ""]
    for i in sorted(lat):
        out.append(f"* {i}: " + ", ".join(f"{v:.2f}" for v in lat[i]['na_max']))
    open(f'{tag}_summary.md', 'w', encoding='utf-8').write("\n".join(out) + "\n")
    print("\n".join(out))

if __name__ == '__main__':
    which = sys.argv[1]
    if which == 'F1': import f1_run; make('F1', 'f1_results.pkl', 'AR(1) exact Gram, s0=4, theta=(1.4,-1.0,1.8,-1.2)', f1_run.ROWS)
    if which == 'F1X': import f1x_run; make('F1X', 'f1x_results.pkl', 'EXTRA: AR(1) exact Gram p=100, P = floor(0.9 log n) nearest nulls (all 2^m lattice sets)', f1x_run.ROWS)
    if which == 'F2': import f2_run; make('F2', 'f2_results.pkl', 'study S5 population design, exact Gram, p=100, P = all nulls', f2_run.ROWS)
